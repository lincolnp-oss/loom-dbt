"""Generated model properties (catalogue) YAML.

`loom generate` publishes a descriptive properties entry for every
generated model that has anything truthful to say: the model's
description from metadata, its output columns (from the general
resolver in loom.output_columns), per-column descriptions from
`column_docs` metadata, and data types that are either Loom-fixed
(the resolver knows them) or declared by the practitioner in
`column_types` metadata using the generic type vocabulary, rendered
per dialect. By default nothing is enforced - there is no
`contract:` stanza and no constraint - so a missing or imperfect
type can never fail a practitioner's build; an unknown type is
omitted rather than guessed. A model that opts in via the
`contract_enforced` envelope key (ADR 0032) instead
gains `config: {contract: {enforced: true}}`, a `data_type` for
every output column rendered in the dialect's adapter-reported
contract spellings, and `not_null` constraints exactly where the
generator's data-test matrix already guarantees them. Validation
fails an opted-in model whose columns are not all typed, so the
stanza below is only ever emitted complete.

The entry lives in the model's single Loom-owned schema document
under `_generated/tests/`: dbt rejects a model described by two schema
files ("resources... may only be described a single time" -
runtime-verified on the quickstart, dbt-duckdb), so where the
generator also emits data tests the properties merge into
`data_<model>.yml` alongside them, and a properties-only document
is named `properties_<model>.yml` in the same directory. One model,
one Loom schema file.

Where the resolver cannot determine a model's columns (SELECT *
generators), the entry carries the model description, plus any
columns the practitioner explicitly documented or typed - those
declarations are the practitioner's own knowledge of their source
columns, published as a partial column list.
"""
from __future__ import annotations

from typing import Any, Mapping

import yaml

from loom.dialects import Dialect, render_contract_data_type, render_data_type
from loom.output_columns import OutputColumn, resolve_output_columns
from loom.output_layout import (
    resolve_contract_enforced,
    resolve_skip_properties_document,
)


def effective_generic_type(
    column: OutputColumn, types_by_key: Mapping[str, str]
) -> str | None:
    """The renderable generic type for one output column, or None.

    A practitioner declaration wins over the Loom-fixed type, but
    only when it is renderable: a bare `decimal` (no precision/scale)
    cannot be rendered for any dialect, so it counts as untyped -
    the completeness validation and this emitter agree on that.
    """
    declared = types_by_key.get(column.name.casefold())
    if isinstance(declared, str):
        value = declared.strip().lower()
        if value == "decimal":
            return None
        return value
    return column.fixed_type


def render_properties(
    data: Mapping[str, Any],
    dialect: Dialect,
    by_name: Mapping[str, Mapping[str, Any]] | None = None,
) -> str | None:
    """A standalone properties document for one model, or None.

    Used for models whose generator emits no data tests. Returns
    None when there is nothing truthful to publish: no model
    description, no derivable columns, and no practitioner-declared
    column documentation or types.
    """
    entry = model_properties_entry(data, dialect, by_name)
    if entry is None:
        return None
    return render_properties_document(entry)


def render_properties_document(model_entry: Mapping[str, Any]) -> str:
    """Serialise one model entry as a Loom-owned schema document."""
    return render_schema_document({"version": 2, "models": [dict(model_entry)]})


def render_schema_document(document: Mapping[str, Any]) -> str:
    """Serialise a full schema document with the Loom header."""
    body = yaml.safe_dump(dict(document), sort_keys=False, allow_unicode=True)
    return "# Generated by Loom\n" + body


def merge_properties(
    test_document: Mapping[str, Any], model_entry: Mapping[str, Any]
) -> dict[str, Any]:
    """Merge a properties entry into a parsed data-test document.

    The data-test document's model entry gains the properties
    description and columns; each tested column gains its data_type
    / description, tested columns keep their tests, and derivable
    columns without tests are appended in SELECT order position.
    """
    merged = dict(test_document)
    models = []
    for model in test_document.get("models") or []:
        if not isinstance(model, dict) or model.get("name") != model_entry.get("name"):
            models.append(model)
            continue
        combined: dict[str, Any] = {"name": model.get("name")}
        if model_entry.get("description"):
            combined["description"] = model_entry["description"]
        if model_entry.get("config"):
            # The enforced-contract stanza is a
            # model-level property like the description.
            combined["config"] = model_entry["config"]
        tested = {
            column["name"].casefold(): column
            for column in model.get("columns") or []
            if isinstance(column, dict) and isinstance(column.get("name"), str)
        }
        columns: list[dict[str, Any]] = []
        seen: set[str] = set()
        for prop_column in model_entry.get("columns") or []:
            key = prop_column["name"].casefold()
            seen.add(key)
            entry = dict(prop_column)
            test_column = tested.get(key)
            if test_column is not None:
                for extra_key, extra_value in test_column.items():
                    if extra_key != "name":
                        entry[extra_key] = extra_value
            columns.append(entry)
        for key, test_column in tested.items():
            if key not in seen:
                columns.append(dict(test_column))
        if columns:
            combined["columns"] = columns
        models.append(combined)
    merged["models"] = models
    return merged


def model_properties_entry(
    data: Mapping[str, Any],
    dialect: Dialect,
    by_name: Mapping[str, Mapping[str, Any]] | None = None,
    not_null_columns: frozenset[str] = frozenset(),
) -> dict[str, Any] | None:
    """The properties entry (parsed-YAML shape) for one model, or None."""
    name = data.get("name")
    if not isinstance(name, str):
        return None
    description = data.get("description")
    if not isinstance(description, str) or not description.strip():
        description = None
    docs = data.get("column_docs")
    if not isinstance(docs, dict):
        docs = {}
    types = data.get("column_types")
    if not isinstance(types, dict):
        types = {}
    # Metadata column references are matched case-insensitively,
    # like every other column reference in Loom.
    docs_by_key = {
        key.casefold(): value
        for key, value in docs.items()
        if isinstance(key, str) and isinstance(value, str)
    }
    types_by_key = {
        key.casefold(): value
        for key, value in types.items()
        if isinstance(key, str) and isinstance(value, str)
    }

    resolved = resolve_output_columns(data, by_name)
    if resolved is not None:
        column_names = [column.name for column in resolved]
        fixed_types = {column.name.casefold(): column.fixed_type for column in resolved}
    else:
        # Undeterminable output set: publish only the columns the
        # practitioner explicitly documented or typed, in declaration
        # order (column_docs first, then types-only columns).
        column_names = []
        seen: set[str] = set()
        for mapping in (docs, types):
            for key in mapping:
                if isinstance(key, str) and key.casefold() not in seen:
                    seen.add(key.casefold())
                    column_names.append(key)
        fixed_types = {}

    if description is None and not column_names:
        return None

    enforced = resolve_contract_enforced(data)
    model_entry: dict[str, Any] = {"name": name}
    if description is not None:
        model_entry["description"] = description
    if enforced:
        model_entry["config"] = {"contract": {"enforced": True}}
    if column_names:
        columns_yaml = []
        for column_name in column_names:
            entry: dict[str, Any] = {"name": column_name}
            generic = types_by_key.get(
                column_name.casefold(), fixed_types.get(column_name.casefold())
            )
            if isinstance(generic, str):
                if enforced:
                    rendered = render_contract_data_type(dialect, generic)
                else:
                    rendered = render_data_type(dialect, generic)
                if rendered is not None:
                    entry["data_type"] = rendered
            declared_doc = docs_by_key.get(column_name.casefold())
            if isinstance(declared_doc, str) and declared_doc.strip():
                entry["description"] = declared_doc
            if (
                enforced
                and column_name.casefold() in not_null_columns
                and data.get("generator") != "scd2_dimension"
            ):
                # not_null exactly where the generator's data-test
                # matrix already guarantees it - no decorative
                # constraints. The SCD2 *view* is the one described
                # model whose materialisation (view) cannot carry
                # constraints in a dbt contract; validation warns
                # about the drop (see contract_warnings).
                entry["constraints"] = [{"type": "not_null"}]
            columns_yaml.append(entry)
        model_entry["columns"] = columns_yaml

    return model_entry


def contract_warnings(entries: list) -> list[str]:
    """Non-fatal enforced-contract warnings for validate/generate.

    One rule in v1: an opted-in SCD2 dimension's business-key
    `not_null` cannot be emitted (dbt view contracts carry names
    and types only), so the drop is announced rather than silent.
    """
    warnings: list[str] = []
    for entry in entries:
        if not entry.is_generated:
            continue
        if entry.data.get("generator") != "scd2_dimension":
            continue
        if resolve_contract_enforced(entry.data):
            warnings.append(
                f"{entry.path}: contract_enforced on "
                f"{entry.data.get('name')!r}: the described model is "
                "the SCD2 view, whose contract carries names and "
                "types only - the business key's not_null constraint "
                "is not emitted"
            )
    return warnings


def properties_optout_warnings(
    entries: list, document: dict[str, Any] | None
) -> list[str]:
    """The safety net for the properties-document opt-out.

    Warn-not-fail, for `loom check`: a model that declares
    `skip_properties_document` hands its dbt description to the
    practitioner's own YAML - when the manifest shows no
    description for the model, that YAML does not exist (or does
    not describe the model), and the model is left with no dbt
    description at all. The opt-out stays the practitioner's
    declaration; the warning exists so opting out and never
    writing the YAML cannot happen silently.
    """
    warnings: list[str] = []
    nodes = document.get("nodes") if isinstance(document, dict) else None
    descriptions: dict[str, Any] = {}
    if isinstance(nodes, dict):
        for node in nodes.values():
            if not isinstance(node, dict):
                continue
            if node.get("resource_type") != "model":
                continue
            name = node.get("name")
            if isinstance(name, str):
                descriptions[name] = node.get("description")
    for entry in entries:
        if not entry.is_generated:
            continue
        if not resolve_skip_properties_document(entry.data):
            continue
        name = entry.data.get("name")
        description = descriptions.get(name) if isinstance(name, str) else None
        if isinstance(description, str) and description.strip():
            continue
        warnings.append(
            f"{entry.path}: model {name!r} declares "
            "skip_properties_document but the manifest shows no "
            "practitioner description for it; the model will have "
            "no dbt description - describe it in your own schema "
            "YAML, or remove the opt-out"
        )
    return warnings
