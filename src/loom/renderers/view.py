from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class ViewRenderer(BaseRenderer):
    """Renderer for the view generator.

    Produces a 3NF reporting view by joining normalized tables
    and selecting a flattened set of columns.

    Every input model is aliased by its own name, so `select_columns`
    references of the form ``<model>.<column>`` resolve against the
    FROM/JOIN clauses. Additional inputs are joined to the first input
    on explicit keys from the instance's ``joins`` entries
    (``{model, on: [key, ...]}``); a multi-input view without explicit
    join keys is rejected rather than cross-joined.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        input_models = params.get("input_models", [])
        select_columns = params.get("select_columns", [])
        if not input_models:
            raise LoomError(f"view instance {name!r} requires at least one input model")

        join_keys: dict[str, list[str]] = {}
        for join in params.get("joins") or []:
            if isinstance(join, dict) and isinstance(join.get("model"), str):
                on = join.get("on")
                join_keys[join["model"]] = (
                    [key for key in on if isinstance(key, str)]
                    if isinstance(on, list)
                    else []
                )

        # Build SELECT clause
        select_parts: list[str] = []
        for col in select_columns:
            expression = col.get("expression")
            if isinstance(expression, str) and expression.strip():
                # The expression item (ADR 0037): verbatim SQL
                # under its alias.
                select_parts.append(f"  {expression} AS {col.get('alias')}")
                continue
            from_ref = col.get("source", "*")
            alias = col.get(
                "alias", from_ref.split(".")[-1] if "." in from_ref else from_ref
            )
            select_parts.append(f"  {from_ref} AS {alias}")

        # Build FROM/JOIN clause: alias each input by its model name and
        # join additional inputs to the first input on explicit keys.
        first = input_models[0]
        from_sql = f"FROM {{{{ ref('{first}') }}}} AS {first}"
        for model in input_models[1:]:
            keys = join_keys.get(model)
            if not keys:
                raise LoomError(
                    f"view instance {name!r}: input model {model!r} requires an "
                    "explicit 'joins' entry with a non-empty 'on' list of join "
                    "keys; Loom does not generate cross joins"
                )
            conditions = " AND ".join(f"{first}.{key} = {model}.{key}" for key in keys)
            from_sql += f"\nLEFT JOIN {{{{ ref('{model}') }}}} AS {model} ON {conditions}"

        select_sql = ",\n".join(select_parts)
        sql = (
            "-- Generated by Loom\n"
            f"-- Generator: view\n"
            "-- Paradigm: threenf\n"
            f"{{{{ config(materialized='view') }}}}\n"
            "SELECT\n"
            f"{select_sql}\n"
            f"{from_sql}"
        )
        return sql

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        """No data tests generated for reporting views."""
        return None
