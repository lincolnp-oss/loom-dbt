from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class MartRenderer(BaseRenderer):
    """Renderer for the mart generator.

    Produces lightweight aggregations directly on staging inputs.
    An empty ``group_by`` is a grand-total aggregation and emits no
    GROUP BY clause.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        input_model = (params.get("input_models") or ["unknown"])[0]
        aggregation = params.get("aggregation", {})
        group_by = aggregation.get("group_by", [])
        measures = aggregation.get("measures", [])

        for measure in measures:
            if not isinstance(measure, dict) or not str(
                measure.get("expression") or ""
            ).strip():
                raise LoomError(
                    f"mart instance {name!r}: every measure requires a "
                    "non-empty 'expression'"
                )

        # Build SELECT clause
        select_parts: list[str] = []
        for g in group_by:
            if isinstance(g, dict):
                # The expression item (ADR 0037): verbatim SQL
                # under its alias.
                select_parts.append(f"  {g.get('expression')} AS {g.get('alias')}")
            else:
                select_parts.append(f"  {g}")
        for measure in measures:
            alias = measure.get("alias", measure.get("column", ""))
            expr = measure.get("expression", alias)
            select_parts.append(f"  {expr} AS {alias}")
        select_parts.append(f"  {dialect.current_timestamp} AS __loaded_at")

        select_sql = ",\n".join(select_parts)

        from_sql = f"FROM {{{{ ref('{input_model}') }}}}"

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: mart\n"
            f"-- Paradigm: hybrid\n"
            f"{{{{ config(materialized='table') }}}}\n"
            f"SELECT\n"
            f"{select_sql}\n"
            f"{from_sql}"
        )
        if group_by:
            grouped = ", ".join(
                g.get("expression", "") if isinstance(g, dict) else g
                for g in group_by
            )
            sql += f"\nGROUP BY {grouped}"
        return sql

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        aggregation = params.get("aggregation", {})
        measures = aggregation.get("measures", [])
        model_name = params.get("name", "")

        if not measures:
            return None

        col_lines = []
        for measure in measures:
            alias = measure.get("alias", measure.get("column", ""))
            col_lines.append(f"      - name: {alias}")
            col_lines.append(f"        tests:")
            col_lines.append(f"          - not_null")

        tests_yaml = (
            "# Generated by Loom\nversion: 2\nmodels:\n"
            f"  - name: {model_name}\n    columns:\n"
            + "\n".join(col_lines) + "\n"
        )
        return tests_yaml
