from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class BridgeRenderer(BaseRenderer):
    """Renderer for the bridge generator (ADR 0036).

    A current-state flattening of a declared hub/link path: the
    anchor hub inner-joined through each step's link to the hub it
    reaches. Rows carry the anchor hash, then each reached hub's
    hash in path order, the build's __loaded_at, and - with
    `weighting: equal` - an equal weighting factor per anchor.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        parent_block = params.get("parent")
        anchor = parent_block.get("model") if isinstance(parent_block, dict) else None
        if not isinstance(anchor, str) or not anchor.startswith("hub_"):
            raise LoomError("bridge requires a 'parent' block naming a hub 'model'")
        path = params.get("path")
        if not isinstance(path, list) or not path:
            raise LoomError("bridge requires a non-empty 'path' list")
        steps: list[tuple[str, str]] = []
        for item in path:
            if (
                not isinstance(item, dict)
                or not isinstance(item.get("link"), str)
                or not isinstance(item.get("hub"), str)
            ):
                raise LoomError(
                    "bridge 'path' entries must be {link, hub} mappings"
                )
            steps.append((item["link"], item["hub"]))
        anchor_hash = f"{anchor[4:]}_hk"
        # Every projection is aliased to its bare column name:
        # ClickHouse retains the qualifier in output column names
        # when the name exists on more than one joined source, so
        # an unaliased `a.customer_hk` materialises under that
        # qualified name and bare references fail (Code 47).
        select_lines = [f"    a.{anchor_hash} AS {anchor_hash}"]
        joins = [f"FROM {{{{ ref('{anchor}') }}}} AS a"]
        previous_alias = "a"
        previous_hub = anchor
        for index, (link, hub) in enumerate(steps):
            link_alias = f"l{index + 1}"
            hub_alias = f"h{index + 1}"
            hub_hash = f"{hub[4:]}_hk"
            previous_hash = f"{previous_hub[4:]}_hk"
            joins.append(
                f"JOIN {{{{ ref('{link}') }}}} AS {link_alias}\n"
                f"    ON {link_alias}.{previous_hash} = {previous_alias}.{previous_hash}"
            )
            joins.append(
                f"JOIN {{{{ ref('{hub}') }}}} AS {hub_alias}\n"
                f"    ON {hub_alias}.{hub_hash} = {link_alias}.{hub_hash}"
            )
            select_lines.append(f"    {hub_alias}.{hub_hash} AS {hub_hash}")
            previous_alias = hub_alias
            previous_hub = hub
        weighting = params.get("weighting")
        if weighting is not None:
            if weighting != "equal":
                raise LoomError(
                    f"bridge weighting {weighting!r} is not supported; "
                    "expected 'equal'"
                )
            select_lines.append(
                f"    1.0 / COUNT(*) OVER (PARTITION BY a.{anchor_hash}) "
                "AS __weighting_factor"
            )
        select_lines.append(
            f"    {dialect.current_timestamp} AS __loaded_at"
        )
        return (
            "-- Generated by Loom\n"
            "-- Generator: bridge\n"
            "{{ config(materialized='table') }}\n"
            "SELECT\n"
            + ",\n".join(select_lines)
            + "\n"
            + "\n".join(joins)
        )

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        name = params.get("name", "unknown")
        if not name.startswith("bridge_"):
            return None
        parent_block = params.get("parent")
        anchor = parent_block.get("model") if isinstance(parent_block, dict) else None
        if not isinstance(anchor, str) or not anchor.startswith("hub_"):
            return None
        lines = [
            "# Generated by Loom",
            "version: 2",
            "models:",
            f"  - name: {name}",
            "    columns:",
            f"      - name: {anchor[4:]}_hk",
            "        tests:",
            "          - not_null",
        ]
        if params.get("weighting") == "equal":
            lines += [
                "      - name: __weighting_factor",
                "        tests:",
                "          - not_null",
            ]
        return "\n".join(lines) + "\n"
