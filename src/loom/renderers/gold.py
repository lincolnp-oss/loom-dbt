from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class GoldRenderer(BaseRenderer):
    """Renderer for the gold generator.

    Produces business aggregates over silver inputs.
    Supports single-input (no JOIN) and multi-input aggregation. Multi-input
    aggregation joins additional inputs to the first input on explicit keys
    from the instance's ``joins`` entries (``{model, on: [key, ...]}``);
    every input is aliased by its model name and group-by columns are
    qualified with the first input's alias, so join keys that exist in
    several inputs are never ambiguous. An aggregation with
    measures but no ``group_by`` is a grand total and emits no GROUP BY
    clause.

    An optional `incremental` block turns an
    aggregate model into grain-period recomputation: the scan
    window over the driving (first) input names the touched
    grains, the batch re-runs the aggregation over the full
    current inputs for exactly those grains, and dbt writes the
    batch under the declared key strategy on the grain. A touched
    grain's value is exact - the same aggregate a rebuild would
    compute at that moment - and its ``__loaded_at`` is
    restamped; untouched grains are not rewritten and keep their
    earlier stamps (§5.2). The block requires aggregate mode with
    a non-empty ``group_by`` and a ``cursor_column``; grand-total
    and pass-through shapes reject it by name. Without the block
    every shape renders exactly as before.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        input_models = params.get("input_models") or []
        if not input_models:
            raise LoomError(
                f"gold instance {name!r} requires 'input_models'"
            )

        aggregation = params.get("aggregation", {})
        if not isinstance(aggregation, dict):
            raise LoomError(f"gold instance {name!r}: 'aggregation' must be a mapping")
        group_by = aggregation.get("group_by", [])
        measures = aggregation.get("measures", [])
        # The grain keys: a string item keys itself; an
        # expression item (ADR 0037) keys its alias, the output
        # column the expression produces.
        group_by_keys = [
            g
            if isinstance(g, str)
            else g.get("alias", "")
            for g in group_by
            if isinstance(g, (str, dict))
        ]

        # No aggregation: simple pass-through with timestamp. Pass-through
        # is single-input only; extra inputs would otherwise be silently
        # dropped.
        if not group_by and not measures:
            if params.get("incremental") is not None:
                raise LoomError(
                    f"gold instance {name!r}: 'incremental' is not "
                    "supported for pass-through gold (no aggregation): "
                    "pass-through has no grain and no key - its output "
                    "is the input's column set - so there is no grain "
                    "an incremental run could recompute; add an "
                    "aggregation with a group_by to declare the grain "
                    ""
                )
            if len(input_models) != 1:
                raise LoomError(
                    f"gold instance {name!r}: pass-through (no aggregation) "
                    "requires exactly one input model; add an aggregation and "
                    "explicit 'joins' entries to combine multiple inputs"
                )
            sql = (
                f"-- Generated by Loom\n"
                f"-- Generator: gold\n"
                f"-- Paradigm: medallion\n"
                f"{{{{ config(materialized='table') }}}}\n"
                f"SELECT\n"
                f"  *,\n"
                f"  {dialect.current_timestamp} AS __loaded_at\n"
                f"FROM {{{{ ref('{input_models[0]}') }}}}"
            )
            return sql

        for measure in measures:
            if not isinstance(measure, dict) or not str(
                measure.get("expression") or ""
            ).strip():
                raise LoomError(
                    f"gold instance {name!r}: every measure requires a "
                    "non-empty 'expression'"
                )

        multi_input = len(input_models) > 1
        first = input_models[0]

        # An `incremental` block turns the
        # aggregation into grain-period recomputation. The grain -
        # the group_by tuple - is the key (a declared unique_key
        # must equal it, §5.4); the cursor over the driving input
        # is required and names the touched grains; the restriction
        # splices ahead of the GROUP BY so the batch re-runs this
        # same aggregation over the full current inputs for exactly
        # those grains. No block: the table render below is
        # unchanged, byte for byte.
        spec = self._incremental_spec(params, default_key=tuple(group_by_keys))
        config = "{{ config(materialized='table') }}"
        restriction = ""
        if spec is not None:
            if not group_by:
                raise LoomError(
                    f"gold instance {name!r}: 'incremental' is not "
                    "supported for a grand total (measures with no "
                    "group_by): the grain would be the whole table, "
                    "so every run would recompute everything and "
                    "'incremental' would be a label on a full "
                    "rebuild; keep table mode, which is honest about "
                    "the cost"
                )
            self._check_incremental_strategy(spec, dialect, model_name=name)
            if spec.strategy == "append":
                raise LoomError(
                    f"gold instance {name!r}: incremental strategy "
                    "'append' is not supported for gold: a "
                    "recomputed grain replaces the stored grain "
                    "row, so the batch must reconcile on the grain - "
                    "an append would load a second copy of every "
                    "touched grain on each rerun; use 'merge' or "
                    "'delete+insert'"
                )
            if set(spec.unique_key) != set(group_by_keys):
                raise LoomError(
                    f"gold instance {name!r}: incremental "
                    f"unique_key {list(spec.unique_key)!r} must "
                    f"equal the aggregation group_by "
                    f"{list(group_by)!r} (in any order): the batch "
                    "computes one row per grain, so the strategy "
                    "must reconcile on that same grain"
                )
            if spec.cursor_column is None:
                raise LoomError(
                    f"gold instance {name!r}: 'incremental' "
                    "requires a 'cursor_column': the cursor over "
                    "the driving input names the grains each run "
                    "recomputes, and gold has no default cursor - "
                    "declare the driving input's event or load "
                    "column"
                )
            aliases = [
                measure.get("alias", measure.get("column", ""))
                for measure in measures
                if isinstance(measure, dict)
            ]
            if spec.cursor_column not in [*group_by_keys, *aliases, "__loaded_at"]:
                raise LoomError(
                    f"gold instance {name!r}: incremental "
                    f"cursor_column {spec.cursor_column!r} is not "
                    "one of the columns this generator emits "
                    "(group_by, measure aliases, __loaded_at): "
                    "the window bound is the target's maximum "
                    "cursor value, so the cursor must be a column "
                    "of the target"
                )
            config = self._incremental_config(spec)
            restriction = self._affected_grain_filter(
                spec,
                grain_columns=list(group_by_keys),
                input_ref=f"{{{{ ref('{first}') }}}}",
                source_alias=first,
            )

        # Build SELECT clause. In multi-input queries the group-by columns
        # are qualified with the first input's alias, because the join keys
        # exist in every joined input by construction.
        select_parts = []
        for g in group_by:
            if isinstance(g, dict):
                # The expression item (ADR 0037): verbatim SQL
                # under its alias, never input-qualified.
                select_parts.append(
                    f"    {g.get('expression')} AS {g.get('alias')}"
                )
            else:
                select_parts.append(f"    {first}.{g}" if multi_input else f"    {g}")
        for measure in measures:
            alias = measure.get("alias", measure.get("column", ""))
            expr = measure.get("expression", alias)
            select_parts.append(f"    {expr} AS {alias}")
        select_parts.append(f"    {dialect.current_timestamp} AS __loaded_at")

        select_sql = ",\n".join(select_parts)

        # Build FROM clause. An incremental single-input query
        # aliases its driving input by model name (as multi-input
        # always does) so the affected-grain restriction can
        # correlate the grain columns against it.
        if not multi_input:
            if spec is not None:
                from_sql = f"FROM {{{{ ref('{first}') }}}} AS {first}"
            else:
                from_sql = f"FROM {{{{ ref('{first}') }}}}"
        else:
            join_keys: dict[str, list[str]] = {}
            for join in params.get("joins") or []:
                if isinstance(join, dict) and isinstance(join.get("model"), str):
                    on = join.get("on")
                    join_keys[join["model"]] = (
                        [key for key in on if isinstance(key, str)]
                        if isinstance(on, list)
                        else []
                    )
            joins = []
            for model in input_models[1:]:
                keys = join_keys.get(model)
                if not keys:
                    raise LoomError(
                        f"gold instance {name!r}: input model {model!r} requires "
                        "an explicit 'joins' entry with a non-empty 'on' list "
                        "of join keys; Loom does not generate cross joins"
                    )
                conditions = " AND ".join(
                    f"{first}.{key} = {model}.{key}" for key in keys
                )
                joins.append(
                    f"LEFT JOIN {{{{ ref('{model}') }}}} AS {model} ON {conditions}"
                )
            from_sql = f"FROM {{{{ ref('{first}') }}}} AS {first}\n" + "\n".join(joins)

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: gold\n"
            f"-- Paradigm: medallion\n"
            f"{config}\n"
            f"SELECT\n"
            f"{select_sql}\n"
            f"{from_sql}"
            f"{restriction}"
        )
        if group_by:
            qualified = ", ".join(
                # An expression item groups by its expression,
                # verbatim, in both input modes.
                g.get("expression", "")
                if isinstance(g, dict)
                else f"{first}.{g}"
                if multi_input
                else g
                for g in group_by
            )
            sql += f"\nGROUP BY {qualified}"
        return sql

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        aggregation = params.get("aggregation", {})
        measures = aggregation.get("measures", [])
        name = params.get("name", "unknown")

        if not measures:
            return None

        col_lines = []
        for measure in measures:
            alias = measure.get("alias", measure.get("column", ""))
            col_lines.append(f"      - name: {alias}")
            col_lines.append(f"        tests:")
            col_lines.append(f"          - not_null")

        tests_yaml = (
            "# Generated by Loom\nversion: 2\nmodels:\n"
            f"  - name: {name}\n    columns:\n"
            + "\n".join(col_lines) + "\n"
        )
        return tests_yaml
