from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class OBTRenderer(BaseRenderer):
    """Renderer for the OBT (One Big Table) generator.

    Produces a wide denormalized table: the source model's own
    declared `columns` projected first, then each joined model's
    declared columns, then a fresh `__loaded_at`.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        source_model = (params.get("input_models") or ["unknown"])[0]
        joins = params.get("joins", [])
        if not joins:
            raise LoomError(
                f"obt instance {name!r} requires a non-empty 'joins' list; "
                "without joins the model would contain only a timestamp"
            )
        columns = params.get("columns")
        if not isinstance(columns, list) or not columns:
            raise LoomError(
                f"obt instance {name!r} requires a non-empty 'columns' list "
                "naming the source model's own columns to project; without "
                "it the model would silently drop every source column and "
                "contain only the joined models' columns"
            )

        # Build SELECT clause. Output names must be unique: when two
        # joins contribute the same column name, later occurrences are
        # aliased with their join alias (j<idx>_<column>).
        select_parts: list[str] = []
        seen_output_names: set[str] = set()
        for col in columns:
            # Items: a string projects the source column; a
            # {source, alias} mapping renames it; an
            # {expression, alias} mapping (ADR 0037) carries
            # verbatim SQL under its alias.
            if isinstance(col, str):
                output_name = col
                fragment = f"  t.{col} AS {col}"
            elif isinstance(col, dict):
                alias = col.get("alias")
                if not isinstance(alias, str):
                    continue
                output_name = alias
                expression = col.get("expression")
                if isinstance(expression, str) and expression.strip():
                    fragment = f"  {expression} AS {alias}"
                elif isinstance(col.get("source"), str):
                    fragment = f"  t.{col['source']} AS {alias}"
                else:
                    continue
            else:
                continue
            # __loaded_at is always emitted last, freshly stamped;
            # projecting the source's copy as well would duplicate it.
            if output_name.casefold() == "__loaded_at" or output_name in seen_output_names:
                continue
            seen_output_names.add(output_name)
            select_parts.append(fragment)
        for idx, join in enumerate(joins):
            alias = f"j{idx}"
            for col in join.get("columns", []):
                output_name = col
                if output_name in seen_output_names:
                    output_name = f"{alias}_{col}"
                seen_output_names.add(output_name)
                select_parts.append(f"  {alias}.{col} AS {output_name}")

        select_parts.append(f"  {dialect.current_timestamp} AS __loaded_at")

        select_sql = ",\n".join(select_parts)

        # Build FROM/JOIN clause. Join keys are compared as text
        # (the dialect's key cast): a normalized hub key is stored as
        # text while a staging key keeps its source type, and strict
        # engines refuse int = text comparisons.
        from_sql = f"FROM {{{{ ref('{source_model}') }}}} AS t"
        for idx, join in enumerate(joins):
            model = join.get("model", "unknown")
            alias = f"j{idx}"
            on_cols = join.get("on", [])
            on_conditions = " AND ".join(
                [
                    f"{self._key_cast(dialect, f't.{k}')} = "
                    f"{self._key_cast(dialect, f'{alias}.{k}')}"
                    for k in on_cols
                ]
            )
            from_sql += (
                f"\nLEFT JOIN {{{{ ref('{model}') }}}} AS {alias} ON {on_conditions}"
            )

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: obt\n"
            f"-- Paradigm: obt\n"
            f"{{{{ config(materialized='table') }}}}\n"
            f"SELECT\n"
            f"{select_sql}\n"
            f"{from_sql}"
        )
        return sql

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        return None
