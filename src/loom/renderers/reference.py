from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer

_MODES = ("latest", "full", "snapshot")


class ReferenceHubRenderer(BaseRenderer):
    """Renderer for the reference_hub generator (ADR 0034).

    Hub-shaped identity for reference code sets: the hash column and
    the code itself, mandatory provenance, always-persistent loads
    (the persistent hub's execution-proven anti-join form, with the
    Databricks merge treatment). Codes are never forgotten because
    an extract omitted them.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        business_key = params.get("business_key", "unknown")
        record_source = params.get("record_source", "unknown")
        input_model = (params.get("input_models") or ["unknown"])[0]
        hash_column = f"{name[4:]}_hk"  # ref_country -> country_hk
        normalized = self._normalize_key(dialect, business_key)
        hash_expr = self._hash_expression(normalized, dialect)

        if dialect.name == "databricks":
            # Provenance is written on first insert only (the
            # hub treatment): a re-observed code keeps its original
            # __record_source and __loaded_at.
            select_clause = (
                "{{ config(materialized='incremental', "
                f"unique_key='{hash_column}', incremental_strategy='merge', "
                "merge_exclude_columns=['__record_source', '__loaded_at']) "
                "}}\n"
                "SELECT DISTINCT"
            )
            incremental_filter = ""
        else:
            select_clause = (
                "{{ config(materialized='incremental', "
                "incremental_strategy='append') }}\n"
                "SELECT DISTINCT"
            )
            incremental_filter = (
                "\n{% if is_incremental() %}\n"
                f"  AND {hash_expr} NOT IN (\n"
                f"    SELECT target.{hash_column} FROM {{{{ this }}}} AS target\n"
                "  )\n"
                "{% endif %}"
            )
        return (
            f"-- Generated by Loom\n"
            f"-- Generator: reference_hub\n"
            f"-- Hash function: {dialect.hash_function}\n"
            f"{select_clause}\n"
            f"    {hash_expr} AS {hash_column},\n"
            f"    {normalized} AS {business_key},\n"
            f"    '{record_source}' AS __record_source,\n"
            f"    {dialect.current_timestamp} AS __loaded_at\n"
            f"FROM {{{{ ref('{input_model}') }}}}\n"
            f"WHERE {business_key} IS NOT NULL"
            f"{incremental_filter}"
        )

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        name = params.get("name", "unknown")
        if not name.startswith("ref_"):
            return None
        business_key = params.get("business_key", "unknown")
        hash_column = f"{name[4:]}_hk"
        return (
            "# Generated by Loom\n"
            "version: 2\n"
            "models:\n"
            f"  - name: {name}\n"
            "    columns:\n"
            f"      - name: {hash_column}\n"
            "        tests:\n"
            "          - unique\n"
            "          - not_null\n"
            f"      - name: {business_key}\n"
            "        tests:\n"
            "          - not_null\n"
        )


class ReferenceTableRenderer(BaseRenderer):
    """Renderer for the reference_table generator (ADR 0034).

    A view flattening one reference hub with one of its satellites:
    `latest` (one row per code), `full` (every satellite history
    row), or `snapshot` (latest per code among rows loaded at or
    before a declared timestamp).
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        mode = params.get("variant", "latest")
        if mode not in _MODES:
            raise LoomError(
                f"reference_table variant {mode!r} is not supported; "
                f"expected one of: {', '.join(_MODES)}"
            )
        ref_hub = params.get("reference_hub")
        satellites = params.get("satellites")
        satellite = (
            satellites[0]
            if isinstance(satellites, list)
            and len(satellites) == 1
            and isinstance(satellites[0], str)
            else None
        )
        business_key = params.get("business_key")
        attributes = params.get("attribute_columns") or []
        if not (
            isinstance(ref_hub, str)
            and isinstance(satellite, str)
            and isinstance(business_key, str)
        ):
            raise LoomError(
                "reference_table requires 'reference_hub', a "
                "one-entry 'satellites' list and 'business_key'"
            )
        if not attributes:
            raise LoomError(
                "reference_table requires a non-empty "
                "'attribute_columns' list"
            )
        hash_column = f"{ref_hub[4:]}_hk"
        # Every projection is aliased to its bare column name: the
        # hash column exists on both joined sources, and ClickHouse
        # retains the qualifier in output column names in that case,
        # so unaliased projections would name the view's columns
        # `h.<col>` / `s.<col>` and bare references would fail.
        attribute_lines = "".join(
            f",\n    s.{column} AS {column}" for column in attributes
        )
        header = (
            f"-- Generated by Loom\n"
            f"-- Generator: reference_table\n"
            f"-- Mode: {mode}\n"
            f"{{{{ config(materialized='view') }}}}\n"
        )
        if mode == "full":
            return (
                header
                + "SELECT\n"
                + f"    h.{hash_column} AS {hash_column},\n"
                + f"    h.{business_key} AS {business_key}"
                + attribute_lines
                + ",\n    s.__record_source AS __record_source,\n"
                + "    s.__loaded_at AS __loaded_at\n"
                + f"FROM {{{{ ref('{ref_hub}') }}}} AS h\n"
                + f"JOIN {{{{ ref('{satellite}') }}}} AS s\n"
                + f"    ON s.{hash_column} = h.{hash_column}"
            )
        snapshot_filter = ""
        if mode == "snapshot":
            timestamp = params.get("snapshot_timestamp")
            if not isinstance(timestamp, str) or not timestamp:
                raise LoomError(
                    "reference_table snapshot mode requires a "
                    "'snapshot_timestamp'"
                )
            snapshot_filter = f"\n    WHERE __loaded_at <= '{timestamp}'"
        inner_attributes = "".join(f",\n        {column}" for column in attributes)
        return (
            header
            + "SELECT\n"
            + f"    h.{hash_column} AS {hash_column},\n"
            + f"    h.{business_key} AS {business_key}"
            + attribute_lines
            + ",\n    s.__record_source AS __record_source,\n"
            + "    s.__loaded_at AS __loaded_at\n"
            + f"FROM {{{{ ref('{ref_hub}') }}}} AS h\n"
            + "JOIN (\n"
            + "    SELECT\n"
            + f"        {hash_column}"
            + inner_attributes
            + ",\n        __record_source,\n"
            + "        __loaded_at,\n"
            + "        ROW_NUMBER() OVER (\n"
            + f"            PARTITION BY {hash_column}\n"
            + "            ORDER BY __loaded_at DESC, __hash_diff DESC\n"
            + "        ) AS rn\n"
            + f"    FROM {{{{ ref('{satellite}') }}}}"
            + snapshot_filter
            + "\n) AS s\n"
            + f"    ON s.{hash_column} = h.{hash_column}\n"
            + "    AND s.rn = 1"
        )

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        name = params.get("name", "unknown")
        business_key = params.get("business_key")
        if not isinstance(business_key, str) or not business_key:
            return None
        mode = params.get("variant", "latest")
        lines = [
            "# Generated by Loom",
            "version: 2",
            "models:",
            f"  - name: {name}",
            "    columns:",
            f"      - name: {business_key}",
            "        tests:",
        ]
        if mode in ("latest", "snapshot"):
            # One flattened row per code in these modes.
            lines.append("          - unique")
        lines.append("          - not_null")
        return "\n".join(lines) + "\n"
