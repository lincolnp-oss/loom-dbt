from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class BronzeRenderer(BaseRenderer):
    """Renderer for the bronze generator.

    Produces a raw load: select all columns from the source
    with a __loaded_at provenance column.

    An optional `incremental` block turns the
    load incremental. Bronze declares no key of its own and its
    source columns are unknowable to Loom, so the block must carry
    its own guard: a declared `unique_key` (the append anti-join
    guard, or the key for merge/delete+insert) or a `cursor_column`
    (a strict cursor window for append - the mirror of fact's
    append semantics - or a scan filter for the key strategies).
    The cross-field rules live in the inventory validators; the
    renderer composes the shared core's fragments.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        source = params.get("inline_source")
        if not isinstance(source, dict):
            raise LoomError(
                f"bronze instance {name!r} requires an 'inline_source' mapping "
                "with 'name' and 'table'"
            )
        source_name = source.get("name")
        source_table = source.get("table")
        if not isinstance(source_name, str) or not source_name.strip():
            raise LoomError(
                f"bronze instance {name!r} requires a non-empty "
                "inline_source 'name'"
            )
        if not isinstance(source_table, str) or not source_table.strip():
            raise LoomError(
                f"bronze instance {name!r} requires a non-empty "
                "inline_source 'table'"
            )

        spec = self._incremental_spec(params)
        config = "{{ config(materialized='table') }}"
        filter_sql = ""
        if spec is not None:
            self._check_incremental_strategy(spec, dialect, model_name=name)
            if spec.strategy == "append":
                # Append-guard shapes emit no unique_key in the
                # config (design §2.2): the guard, not dbt, enforces
                # identity.
                config = self._incremental_config(
                    replace(spec, unique_key=())
                )
                if spec.unique_key:
                    # The declared key is the guard (flavour A). The
                    # raw load has no WHERE clause of its own, so
                    # the guard opens one.
                    if len(spec.unique_key) == 1:
                        key = spec.unique_key[0]
                        filter_sql = self._anti_join_filter(
                            key, key, where=True
                        )
                    else:
                        filter_sql = self._anti_join_filter_multi(
                            [(key, key) for key in spec.unique_key],
                            where=True,
                        )
                else:
                    # Cursor-only append: the strict window (rows
                    # after the target maximum), so a rerun never
                    # re-appends the boundary batch.
                    filter_sql = self._cursor_predicate(spec, strict=True)
            else:
                config = self._incremental_config(spec)
                if spec.cursor_column is not None:
                    # Key strategies: the cursor only bounds the
                    # scan; dbt reconciles by key, boundary rows
                    # included.
                    filter_sql = self._cursor_predicate(spec)

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: bronze\n"
            f"-- Paradigm: medallion\n"
            f"{config}\n"
            f"SELECT\n"
            f"  *,\n"
            f"  {dialect.current_timestamp} AS __loaded_at\n"
            f"FROM {{{{ source('{source_name}', '{source_table}') }}}}"
            f"{filter_sql}"
        )
        return sql

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        return None
