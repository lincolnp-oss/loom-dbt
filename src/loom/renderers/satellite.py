from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer

_VARIANTS = (
    "standard",
    "non_historised",
    "record_tracking",
    "multi_active",
    "effectivity",
)


class SatelliteRenderer(BaseRenderer):
    """Renderer for the satellite generator (ADR 0028).

    One parameterised generator with a ``variant`` branch:

    - ``standard``: historised satellite. An append-only incremental
      table keyed by the parent hub/link hash, carrying a stored
      ``__hash_diff`` over the payload; a load inserts a row when the
      hash diff differs from the latest held row for that key. A
      second output, the ``<name>_current`` view, exposes the latest
      row per parent key (without the hash diff).
    - ``non_historised``: immutable-event satellite. An append-only
      incremental table that inserts a (parent key, payload) row
      only when an identical row is not already held - identity is
      decided by a hash diff recomputed over the held rows, never
      stored.
    - ``record_tracking``: appearance/absence tracking with no
      payload. Inserts an appearance row when a parent key shows up
      in the input while not currently active for the instance's
      record source, and a deletion row (``__is_deleted``) when a
      currently active key is absent from the input. This is the
      vault's deletion story.
    - ``multi_active`` (ADR 0028): a standard satellite whose
      grain gains a declared ``subsequence_key`` - several attribute
      rows per parent key per load, latest-row resolution per
      (parent key, subsequence key); it emits the current view too.
    - ``effectivity`` (ADR 0028): a link satellite with no
      payload that end-dates relationships. The table is a presence
      log (one row per relationship per load batch in which it is
      present); the generated ``<name>_windows`` view derives the
      effectivity date windows (__valid_from / __valid_to) from it.

    Provenance is mandatory (ADR 0028): every variant emits
    ``__loaded_at`` and ``__record_source`` on every row. The
    satellite joins its input to the parent on the computed parent
    hash, so it never carries a key the parent does not hold.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        variant = params.get("variant", "standard")
        if variant not in _VARIANTS:
            raise LoomError(
                f"satellite variant {variant!r} is not supported; "
                f"expected one of: {', '.join(_VARIANTS)}"
            )
        if output_path is not None:
            # Derived views (the CLI asks for them by name): the
            # current-state view for standard / multi_active, the
            # effectivity windows view for effectivity.
            if str(output_path) == "windows":
                if variant != "effectivity":
                    raise LoomError(
                        "only the effectivity satellite variant has "
                        "a windows view"
                    )
                return self._render_windows_view(params, dialect)
            if variant not in ("standard", "multi_active"):
                raise LoomError(
                    "only the standard and multi_active satellite "
                    "variants have a current-state view"
                )
            return self._render_current_view(params, dialect, variant)
        if variant == "non_historised":
            return self._render_non_historised(params, dialect)
        if variant == "record_tracking":
            return self._render_record_tracking(params, dialect)
        if variant == "multi_active":
            return self._render_multi_active(params, dialect)
        if variant == "effectivity":
            return self._render_effectivity(params, dialect)
        return self._render_standard(params, dialect)

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        name = params.get("name", "unknown")
        if not name.startswith("sat_"):
            return None
        variant = params.get("variant", "standard")
        try:
            hash_column, _, _ = self._parent_hash(params, dialect)
        except LoomError:
            return None

        # No `relationships` test to the parent: a satellite is
        # durable history while a current-retention hub forgets
        # identities that leave the extract, so satellite rows
        # legitimately outlive their parent rows (ADR 0028). The
        # load-time parent join is the integrity mechanism; a
        # relationships test would fail on correct history.
        lines = [
            "# Generated by Loom",
            "version: 2",
            "models:",
            f"  - name: {name}",
            "    columns:",
            f"      - name: {hash_column}",
            "        tests:",
            "          - not_null",
        ]
        if variant in ("standard", "multi_active"):
            lines += [
                "      - name: __hash_diff",
                "        tests:",
                "          - not_null",
            ]
        if variant == "multi_active":
            subsequence = params.get("subsequence_key")
            if isinstance(subsequence, str) and subsequence:
                lines += [
                    f"      - name: {subsequence}",
                    "        tests:",
                    "          - not_null",
                ]
        if variant == "effectivity":
            try:
                _, _, driving_column = self._driving_endpoint(params)
            except LoomError:
                driving_column = None
            if driving_column is not None:
                lines += [
                    f"      - name: {driving_column}",
                    "        tests:",
                    "          - not_null",
                ]
        lines += [
            "      - name: __loaded_at",
            "        tests:",
            "          - not_null",
            "      - name: __record_source",
            "        tests:",
            "          - not_null",
        ]
        if variant == "record_tracking":
            lines += [
                "      - name: __is_deleted",
                "        tests:",
                "          - not_null",
            ]
        return "\n".join(lines) + "\n"

    # -- shared shape -------------------------------------------------

    def _parent_hash(
        self, params: dict, dialect: Dialect, alias: str = "s"
    ) -> tuple[str, str, str]:
        """(hash column, hash expression over the input, parent model).

        Mirrors the hub/link renderers' hash construction exactly, so
        the satellite's computed parent hash equals the parent's own
        hash column value for the same input keys.
        """
        parent_block = params.get("parent")
        parent = (
            parent_block.get("model")
            if isinstance(parent_block, dict)
            else None
        )
        if not isinstance(parent, str) or not parent:
            raise LoomError(
                "satellite requires a 'parent' block with a 'model'"
            )
        endpoints = parent_block.get("endpoints")
        if isinstance(endpoints, list) and endpoints:
            # The parent link's endpoints in declared order
            # (ADR 0030), then the normalized dependent-child key
            # when the link declares one - the satellite's computed
            # parent hash must equal the link's own hash at any
            # arity.
            endpoint_keys = [
                item.get("key")
                for item in endpoints
                if isinstance(item, dict)
            ]
            if not endpoint_keys or not all(
                isinstance(key, str) and key for key in endpoint_keys
            ):
                raise LoomError(
                    "satellite with a link parent requires the "
                    "parent block's 'endpoints' to carry a 'key' "
                    "for every endpoint"
                )
            components = [
                self._hash_expression(
                    self._normalize_key(dialect, f"{alias}.{key}"), dialect
                )
                for key in endpoint_keys
            ]
            dependent_key = parent_block.get("dependent_child_key")
            if isinstance(dependent_key, str) and dependent_key:
                components.append(
                    self._normalize_key(dialect, f"{alias}.{dependent_key}")
                )
            link_hash = self._hash_expression(
                self._concat_expression(components, dialect), dialect
            )
            return f"{parent[5:]}_hk", link_hash, parent
        parent_key = parent_block.get("key")
        if not isinstance(parent_key, str) or not parent_key:
            raise LoomError(
                "satellite's parent block requires a 'key' for a "
                "hub parent (or 'endpoints' for a link parent)"
            )
        hash_expr = self._hash_expression(
            self._normalize_key(dialect, f"{alias}.{parent_key}"), dialect
        )
        return f"{parent[4:]}_hk", hash_expr, parent

    def _staged_cte(self, params: dict, dialect: Dialect, with_diff: bool) -> str:
        """The input joined to its parent, payload projected."""
        input_model = (params.get("input_models") or ["unknown"])[0]
        record_source = params.get("record_source", "unknown")
        hash_column, hash_expr, parent = self._parent_hash(params, dialect)
        attributes = params.get("attribute_columns") or []
        diff_line = ""
        if with_diff:
            diff_expr = self._hash_diff_expression(
                [f"s.{column}" for column in attributes], dialect
            )
            diff_line = f",\n        {diff_expr} AS __hash_diff"
        attribute_lines = "".join(f",\n        s.{column}" for column in attributes)
        return (
            f"WITH staged AS (\n"
            f"    SELECT\n"
            f"        {hash_expr} AS {hash_column}"
            f"{diff_line}"
            f"{attribute_lines},\n"
            f"        {dialect.current_timestamp} AS __loaded_at,\n"
            f"        '{record_source}' AS __record_source\n"
            f"    FROM {{{{ ref('{input_model}') }}}} AS s\n"
            f"    JOIN {{{{ ref('{parent}') }}}} AS p\n"
            f"        ON {hash_expr} = p.{hash_column}\n"
            f")"
        )

    def _header(self, variant: str, dialect: Dialect) -> str:
        return (
            f"-- Generated by Loom\n"
            f"-- Generator: satellite\n"
            f"-- Variant: {variant}\n"
            f"-- Hash function: {dialect.hash_function}\n"
            f"{{{{ config(materialized='incremental', "
            f"incremental_strategy='append') }}}}\n"
        )

    # -- variants -------------------------------------------------------

    def _render_standard(self, params: dict, dialect: Dialect) -> str:
        attributes = params.get("attribute_columns") or []
        if not attributes:
            raise LoomError(
                "standard satellite requires a non-empty "
                "'attribute_columns' list"
            )
        hash_column, _, _ = self._parent_hash(params, dialect)
        staged = self._staged_cte(params, dialect, with_diff=True)
        attribute_lines = "".join(f",\n    st.{column}" for column in attributes)
        return (
            self._header("standard", dialect)
            + staged
            + "\n{% if is_incremental() %}\n"
            + ", latest AS (\n"
            + "    SELECT "
            + f"{hash_column}, __hash_diff\n"
            + "    FROM (\n"
            + "        SELECT\n"
            + f"            {hash_column},\n"
            + "            __hash_diff,\n"
            + "            ROW_NUMBER() OVER (\n"
            + f"                PARTITION BY {hash_column}\n"
            + "                ORDER BY __loaded_at DESC, __hash_diff DESC\n"
            + "            ) AS rn\n"
            + "        FROM {{ this }}\n"
            + "    ) AS ranked\n"
            + "    WHERE rn = 1\n"
            + ")\n"
            + "{% endif %}\n"
            + "SELECT\n"
            + f"    st.{hash_column},\n"
            + "    st.__hash_diff"
            + attribute_lines
            + ",\n    st.__loaded_at,\n"
            + "    st.__record_source\n"
            + "FROM staged AS st\n"
            + "{% if is_incremental() %}\n"
            + "LEFT JOIN latest AS l\n"
            + f"    ON st.{hash_column} = l.{hash_column}\n"
            + f"WHERE l.{hash_column} IS NULL\n"
            + "    OR st.__hash_diff <> l.__hash_diff\n"
            + "{% endif %}"
        )

    def _render_current_view(
        self, params: dict, dialect: Dialect, variant: str = "standard"
    ) -> str:
        name = params.get("name", "unknown")
        attributes = params.get("attribute_columns") or []
        hash_column, _, _ = self._parent_hash(params, dialect)
        subsequence = params.get("subsequence_key")
        multi = variant == "multi_active" and isinstance(subsequence, str)
        attribute_lines = "".join(f",\n        {column}" for column in attributes)
        outer_attributes = "".join(f",\n    {column}" for column in attributes)
        inner_subsequence = f",\n        {subsequence}" if multi else ""
        outer_subsequence = f",\n    {subsequence}" if multi else ""
        partition = (
            f"{hash_column}, {subsequence}" if multi else hash_column
        )
        return (
            f"-- Generated by Loom\n"
            f"-- Generator: satellite\n"
            f"-- View: current state of {name}\n"
            f"SELECT\n"
            f"    {hash_column}"
            f"{outer_subsequence}"
            f"{outer_attributes},\n"
            f"    __loaded_at,\n"
            f"    __record_source\n"
            f"FROM (\n"
            f"    SELECT\n"
            f"        {hash_column}"
            f"{inner_subsequence}"
            f"{attribute_lines},\n"
            f"        __loaded_at,\n"
            f"        __record_source,\n"
            f"        ROW_NUMBER() OVER (\n"
            f"            PARTITION BY {partition}\n"
            f"            ORDER BY __loaded_at DESC, __hash_diff DESC\n"
            f"        ) AS rn\n"
            f"    FROM {{{{ ref('{name}') }}}}\n"
            f") AS ranked\n"
            f"WHERE rn = 1"
        )

    def _driving_endpoint(
        self, params: dict
    ) -> tuple[str, str, str]:
        """(hub name, key column, hash column) of the driving endpoint.

        The effectivity variant's ``driving_key`` names one of the
        parent link's endpoint key columns; the driving hash column
        is that endpoint hub's hash column.
        """
        driving_key = params.get("driving_key")
        if not isinstance(driving_key, str) or not driving_key:
            raise LoomError(
                "effectivity satellite requires a 'driving_key'"
            )
        endpoints: list[tuple[str, str]] = []
        parent_block = params.get("parent")
        declared = (
            parent_block.get("endpoints")
            if isinstance(parent_block, dict)
            else None
        )
        if isinstance(declared, list):
            for item in declared:
                if (
                    isinstance(item, dict)
                    and isinstance(item.get("hub"), str)
                    and isinstance(item.get("key"), str)
                ):
                    endpoints.append((item["hub"], item["key"]))
        for hub, key in endpoints:
            if key == driving_key:
                return hub, key, f"{hub[4:]}_hk"
        raise LoomError(
            f"effectivity 'driving_key' {driving_key!r} is not one of "
            "the parent link's endpoint keys"
        )

    def _render_multi_active(self, params: dict, dialect: Dialect) -> str:
        attributes = params.get("attribute_columns") or []
        if not attributes:
            raise LoomError(
                "multi_active satellite requires a non-empty "
                "'attribute_columns' list"
            )
        subsequence = params.get("subsequence_key")
        if not isinstance(subsequence, str) or not subsequence:
            raise LoomError(
                "multi_active satellite requires a 'subsequence_key'"
            )
        hash_column, hash_expr, parent = self._parent_hash(params, dialect)
        input_model = (params.get("input_models") or ["unknown"])[0]
        record_source = params.get("record_source", "unknown")
        diff_expr = self._hash_diff_expression(
            [f"s.{column}" for column in attributes], dialect
        )
        attribute_lines = "".join(f",\n        s.{column}" for column in attributes)
        outer_attributes = "".join(f",\n    st.{column}" for column in attributes)
        staged = (
            f"WITH staged AS (\n"
            f"    SELECT\n"
            f"        {hash_expr} AS {hash_column},\n"
            f"        {diff_expr} AS __hash_diff,\n"
            f"        s.{subsequence} AS {subsequence}"
            f"{attribute_lines},\n"
            f"        {dialect.current_timestamp} AS __loaded_at,\n"
            f"        '{record_source}' AS __record_source\n"
            f"    FROM {{{{ ref('{input_model}') }}}} AS s\n"
            f"    JOIN {{{{ ref('{parent}') }}}} AS p\n"
            f"        ON {hash_expr} = p.{hash_column}\n"
            f")"
        )
        return (
            self._header("multi_active", dialect)
            + staged
            + "\n{% if is_incremental() %}\n"
            + ", latest AS (\n"
            + "    SELECT "
            + f"{hash_column}, {subsequence}, __hash_diff\n"
            + "    FROM (\n"
            + "        SELECT\n"
            + f"            {hash_column},\n"
            + f"            {subsequence},\n"
            + "            __hash_diff,\n"
            + "            ROW_NUMBER() OVER (\n"
            + f"                PARTITION BY {hash_column}, {subsequence}\n"
            + "                ORDER BY __loaded_at DESC, __hash_diff DESC\n"
            + "            ) AS rn\n"
            + "        FROM {{ this }}\n"
            + "    ) AS ranked\n"
            + "    WHERE rn = 1\n"
            + ")\n"
            + "{% endif %}\n"
            + "SELECT\n"
            + f"    st.{hash_column},\n"
            + "    st.__hash_diff,\n"
            + f"    st.{subsequence}"
            + outer_attributes
            + ",\n    st.__loaded_at,\n"
            + "    st.__record_source\n"
            + "FROM staged AS st\n"
            + "{% if is_incremental() %}\n"
            + "LEFT JOIN latest AS l\n"
            + f"    ON st.{hash_column} = l.{hash_column}\n"
            + f"    AND st.{subsequence} = l.{subsequence}\n"
            + f"WHERE l.{hash_column} IS NULL\n"
            + "    OR st.__hash_diff <> l.__hash_diff\n"
            + "{% endif %}"
        )

    def _render_effectivity(self, params: dict, dialect: Dialect) -> str:
        if params.get("attribute_columns"):
            raise LoomError(
                "effectivity satellite takes no 'attribute_columns' "
                "(it tracks relationship presence, not payload)"
            )
        parent_block = params.get("parent")
        if not (
            isinstance(parent_block, dict)
            and isinstance(parent_block.get("endpoints"), list)
            and parent_block.get("endpoints")
        ):
            raise LoomError(
                "effectivity satellite requires a link parent "
                "(a parent block with 'endpoints')"
            )
        hash_column, hash_expr, parent = self._parent_hash(params, dialect)
        _, driving_key, driving_column = self._driving_endpoint(params)
        driving_expr = self._hash_expression(
            self._normalize_key(dialect, f"s.{driving_key}"), dialect
        )
        input_model = (params.get("input_models") or ["unknown"])[0]
        record_source = params.get("record_source", "unknown")
        staged = (
            f"WITH staged AS (\n"
            f"    SELECT DISTINCT\n"
            f"        {hash_expr} AS {hash_column},\n"
            f"        {driving_expr} AS {driving_column},\n"
            f"        {dialect.current_timestamp} AS __loaded_at,\n"
            f"        '{record_source}' AS __record_source\n"
            f"    FROM {{{{ ref('{input_model}') }}}} AS s\n"
            f"    JOIN {{{{ ref('{parent}') }}}} AS p\n"
            f"        ON {hash_expr} = p.{hash_column}\n"
            f")"
        )
        return (
            self._header("effectivity", dialect)
            + staged
            + "\nSELECT\n"
            + f"    st.{hash_column},\n"
            + f"    st.{driving_column},\n"
            + "    st.__loaded_at,\n"
            + "    st.__record_source\n"
            + "FROM staged AS st\n"
            + "{% if is_incremental() %}\n"
            + "WHERE NOT EXISTS (\n"
            + "    SELECT 1\n"
            + "    FROM {{ this }} AS t\n"
            + f"    WHERE t.{hash_column} = st.{hash_column}\n"
            + "      AND t.__loaded_at = st.__loaded_at\n"
            + ")\n"
            + "{% endif %}"
        )

    def _render_windows_view(self, params: dict, dialect: Dialect) -> str:
        name = params.get("name", "unknown")
        hash_column, _, _ = self._parent_hash(params, dialect)
        _, _, driving_column = self._driving_endpoint(params)
        return (
            f"-- Generated by Loom\n"
            f"-- Generator: satellite\n"
            f"-- View: effectivity windows of {name}\n"
            f"WITH calendar AS (\n"
            f"    SELECT DISTINCT __loaded_at AS ldts\n"
            f"    FROM {{{{ ref('{name}') }}}}\n"
            f"),\n"
            f"pairs AS (\n"
            f"    SELECT DISTINCT {hash_column}, {driving_column}\n"
            f"    FROM {{{{ ref('{name}') }}}}\n"
            f"),\n"
            f"grid AS (\n"
            f"    SELECT\n"
            # Aliased to the bare names: the islands CTE consumes
            # these by bare name, and ClickHouse retains the
            # qualifier in subquery output names when the name
            # exists on more than one joined source (Code 47).
            f"        p.{hash_column} AS {hash_column},\n"
            f"        p.{driving_column} AS {driving_column},\n"
            f"        c.ldts AS ldts,\n"
            f"        CASE WHEN s.{hash_column} IS NOT NULL "
            f"THEN 1 ELSE 0 END AS present,\n"
            f"        LEAD(c.ldts) OVER (\n"
            f"            PARTITION BY p.{hash_column}\n"
            f"            ORDER BY c.ldts\n"
            f"        ) AS next_ldts\n"
            f"    FROM pairs AS p\n"
            f"    CROSS JOIN calendar AS c\n"
            f"    LEFT JOIN {{{{ ref('{name}') }}}} AS s\n"
            f"        ON s.{hash_column} = p.{hash_column}\n"
            f"        AND s.__loaded_at = c.ldts\n"
            f"),\n"
            f"islands AS (\n"
            f"    SELECT\n"
            f"        {hash_column},\n"
            f"        {driving_column},\n"
            f"        ldts,\n"
            f"        present,\n"
            f"        next_ldts,\n"
            f"        ROW_NUMBER() OVER (\n"
            f"            PARTITION BY {hash_column} ORDER BY ldts\n"
            f"        ) - ROW_NUMBER() OVER (\n"
            f"            PARTITION BY {hash_column}, present ORDER BY ldts\n"
            f"        ) AS island\n"
            f"    FROM grid\n"
            f"),\n"
            f"spans AS (\n"
            f"    SELECT\n"
            f"        {hash_column},\n"
            f"        {driving_column},\n"
            f"        ldts,\n"
            f"        next_ldts,\n"
            f"        island,\n"
            f"        MAX(ldts) OVER (\n"
            f"            PARTITION BY {hash_column}, island\n"
            f"        ) AS island_end\n"
            f"    FROM islands\n"
            f"    WHERE present = 1\n"
            f")\n"
            f"SELECT\n"
            f"    {hash_column},\n"
            f"    {driving_column},\n"
            f"    MIN(ldts) AS __valid_from,\n"
            # __valid_to is the last span row's next batch (NULL while
            # the window reaches the latest observed batch) - a plain
            # MAX(next_ldts) would wrongly close open windows, since
            # aggregates ignore the final row's NULL.
            f"    MAX(CASE WHEN ldts = island_end THEN next_ldts END) "
            f"AS __valid_to\n"
            f"FROM spans\n"
            f"GROUP BY {hash_column}, {driving_column}, island"
        )

    def _render_non_historised(self, params: dict, dialect: Dialect) -> str:
        attributes = params.get("attribute_columns") or []
        if not attributes:
            raise LoomError(
                "non_historised satellite requires a non-empty "
                "'attribute_columns' list"
            )
        hash_column, _, _ = self._parent_hash(params, dialect)
        staged = self._staged_cte(params, dialect, with_diff=True)
        held_diff = self._hash_diff_expression(
            [f"t.{column}" for column in attributes], dialect
        )
        attribute_lines = "".join(f",\n    st.{column}" for column in attributes)
        return (
            self._header("non_historised", dialect)
            + staged
            + "\nSELECT\n"
            + f"    st.{hash_column}"
            + attribute_lines
            + ",\n    st.__loaded_at,\n"
            + "    st.__record_source\n"
            + "FROM staged AS st\n"
            + "{% if is_incremental() %}\n"
            + "WHERE NOT EXISTS (\n"
            + "    SELECT 1\n"
            + "    FROM {{ this }} AS t\n"
            + f"    WHERE t.{hash_column} = st.{hash_column}\n"
            + f"      AND {held_diff} = st.__hash_diff\n"
            + ")\n"
            + "{% endif %}"
        )

    def _render_record_tracking(self, params: dict, dialect: Dialect) -> str:
        if params.get("attribute_columns"):
            raise LoomError(
                "record_tracking satellite takes no 'attribute_columns' "
                "(it tracks appearance and absence, not payload)"
            )
        hash_column, hash_expr, parent = self._parent_hash(params, dialect)
        input_model = (params.get("input_models") or ["unknown"])[0]
        record_source = params.get("record_source", "unknown")
        false_literal = self._bool_literal(dialect, False)
        true_literal = self._bool_literal(dialect, True)
        timestamp = dialect.current_timestamp
        return (
            self._header("record_tracking", dialect)
            + "WITH present AS (\n"
            + "    SELECT DISTINCT\n"
            + f"        {hash_expr} AS {hash_column}\n"
            + f"    FROM {{{{ ref('{input_model}') }}}} AS s\n"
            + f"    JOIN {{{{ ref('{parent}') }}}} AS p\n"
            + f"        ON {hash_expr} = p.{hash_column}\n"
            + ")\n"
            + "{% if is_incremental() %}\n"
            + ", latest_state AS (\n"
            + f"    SELECT {hash_column}, __is_deleted\n"
            + "    FROM (\n"
            + "        SELECT\n"
            + f"            {hash_column},\n"
            + "            __is_deleted,\n"
            + "            ROW_NUMBER() OVER (\n"
            + f"                PARTITION BY {hash_column}\n"
            + "                ORDER BY __loaded_at DESC, "
            + "__is_deleted DESC\n"
            + "            ) AS rn\n"
            + "        FROM {{ this }}\n"
            + "    ) AS ranked\n"
            + "    WHERE rn = 1\n"
            + ")\n"
            + "{% endif %}\n"
            + "SELECT\n"
            + f"    p.{hash_column},\n"
            + f"    {timestamp} AS __loaded_at,\n"
            + f"    '{record_source}' AS __record_source,\n"
            + f"    {false_literal} AS __is_deleted\n"
            + "FROM present AS p\n"
            + "{% if is_incremental() %}\n"
            + "LEFT JOIN latest_state AS l\n"
            + f"    ON p.{hash_column} = l.{hash_column}\n"
            + f"WHERE l.{hash_column} IS NULL\n"
            + f"    OR l.__is_deleted = {true_literal}\n"
            + "UNION ALL\n"
            + "SELECT\n"
            + f"    l.{hash_column},\n"
            + f"    {timestamp} AS __loaded_at,\n"
            + f"    '{record_source}' AS __record_source,\n"
            + f"    {true_literal} AS __is_deleted\n"
            + "FROM latest_state AS l\n"
            + f"WHERE l.__is_deleted = {false_literal}\n"
            + f"  AND l.{hash_column} NOT IN (\n"
            + f"        SELECT {hash_column} FROM present\n"
            + "    )\n"
            + "{% endif %}"
        )

    @staticmethod
    def _bool_literal(dialect: Dialect, value: bool) -> str:
        if dialect.name == "azuresynapse":
            # T-SQL has no boolean literal; __is_deleted is a BIT.
            return f"CAST({1 if value else 0} AS BIT)"
        return "TRUE" if value else "FALSE"
