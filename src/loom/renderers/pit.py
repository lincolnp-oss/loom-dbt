from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer

GHOST_TIMESTAMP = "0001-01-01 00:00:00"


class PitRenderer(BaseRenderer):
    """Renderer for the pit generator (ADR 0035).

    A point-in-time table over one hub or link parent: one row per
    (parent key, snapshot date) with, per declared satellite, the
    load timestamp of the satellite row effective at that date -
    or the ghost timestamp when the key has no such row. Snapshot
    dates are the load calendar: the distinct __loaded_at values
    across the declared satellites.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        parent_block = params.get("parent")
        parent = parent_block.get("model") if isinstance(parent_block, dict) else None
        if not isinstance(parent, str) or not parent:
            raise LoomError("pit requires a 'parent' block with a 'model'")
        satellites = params.get("satellites")
        if (
            not isinstance(satellites, list)
            or not satellites
            or not all(isinstance(item, str) and item for item in satellites)
        ):
            raise LoomError("pit requires a non-empty 'satellites' list")
        if isinstance(parent_block, dict) and isinstance(
            parent_block.get("endpoints"), list
        ):
            hash_column = f"{parent[5:]}_hk"
        else:
            hash_column = f"{parent[4:]}_hk"
        ghost = dialect.timestamp_literal_template.format(value=GHOST_TIMESTAMP)
        calendar_branches = "\n        UNION ALL\n        ".join(
            f"SELECT __loaded_at FROM {{{{ ref('{satellite}') }}}}"
            for satellite in satellites
        )
        resolutions = ""
        for satellite in satellites:
            resolutions += (
                f",\n    COALESCE(\n"
                f"        (SELECT MAX(s.__loaded_at)\n"
                f"         FROM {{{{ ref('{satellite}') }}}} AS s\n"
                f"         WHERE s.{hash_column} = k.{hash_column}\n"
                f"           AND s.__loaded_at <= snap.__snapshot_date),\n"
                f"        {ghost}\n"
                f"    ) AS __{satellite}_ldts"
            )
        return (
            f"-- Generated by Loom\n"
            f"-- Generator: pit\n"
            f"{{{{ config(materialized='table') }}}}\n"
            f"WITH snapshots AS (\n"
            f"    SELECT DISTINCT __loaded_at AS __snapshot_date\n"
            f"    FROM (\n"
            f"        {calendar_branches}\n"
            f"    ) AS loads\n"
            f"),\n"
            f"keys AS (\n"
            f"    SELECT {hash_column}\n"
            f"    FROM {{{{ ref('{parent}') }}}}\n"
            f")\n"
            f"SELECT\n"
            f"    k.{hash_column},\n"
            f"    snap.__snapshot_date"
            f"{resolutions}\n"
            f"FROM keys AS k\n"
            f"CROSS JOIN snapshots AS snap"
        )

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        name = params.get("name", "unknown")
        if not name.startswith("pit_"):
            return None
        parent_block = params.get("parent")
        parent = parent_block.get("model") if isinstance(parent_block, dict) else None
        if not isinstance(parent, str) or not parent:
            return None
        if isinstance(parent_block, dict) and isinstance(
            parent_block.get("endpoints"), list
        ):
            hash_column = f"{parent[5:]}_hk"
        else:
            hash_column = f"{parent[4:]}_hk"
        return (
            "# Generated by Loom\n"
            "version: 2\n"
            "models:\n"
            f"  - name: {name}\n"
            "    columns:\n"
            f"      - name: {hash_column}\n"
            "        tests:\n"
            "          - not_null\n"
            "      - name: __snapshot_date\n"
            "        tests:\n"
            "          - not_null\n"
        )
