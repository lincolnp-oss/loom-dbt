from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.renderers.base import BaseRenderer


class StagingRenderer(BaseRenderer):
    """Renderer for the staging generator.

    Produces column projection SQL with source() references.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        source_ref = params.get("source_ref")
        inline_source = params.get("inline_source")
        columns = params.get("columns")
        name = params.get("name", "unknown")
        if columns is not None and len(columns) == 0:
            # An explicit empty projection would silently become
            # SELECT *, contradicting the explicit-projection contract.
            raise ValueError(
                f"staging instance {name!r} requires a non-empty 'columns' list"
            )

        # The `filter` parameter (ADR 0038): a verbatim predicate
        # carried into a WHERE over the source scan, whichever
        # sourcing form and projection shape the instance takes.
        # Absent, the renders below are unchanged, byte for byte.
        row_filter = params.get("filter")
        where_sql = (
            f"\nWHERE {row_filter}"
            if isinstance(row_filter, str) and row_filter.strip()
            else ""
        )

        if source_ref and isinstance(source_ref, dict):
            return self._render_source_ref(
                source_ref, columns, dialect, name, where_sql
            )
        elif inline_source and isinstance(inline_source, dict):
            return self._render_inline_source(
                inline_source, columns, dialect, name, where_sql
            )
        else:
            raise ValueError(
                f"staging instance {name!r} requires source_ref or inline_source"
            )

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        # Staging does not generate dbt data tests
        return None

    def _render_source_ref(
        self,
        source_ref: dict,
        columns: list | None,
        dialect: Dialect,
        name: str,
        where_sql: str = "",
    ) -> str:
        # No 'unknown' fallbacks (pi-review P2): validation
        # requires name and table, and an unvalidated path must
        # fail here in code rather than emit a placeholder
        # literal into generated SQL.
        source_name = source_ref.get("name")
        table_name = source_ref.get("table")
        if not source_name or not table_name:
            raise ValueError(
                f"staging instance {name!r} requires source_ref "
                "'name' and 'table'"
            )

        if not columns:
            return (
                f"-- Generated by Loom\n"
                f"-- Source: {source_name}.{table_name}\n"
                "SELECT *,\n"
                f"  {dialect.current_timestamp} AS __loaded_at\n"
                f"FROM {{{{ source('{source_name}', '{table_name}') }}}}"
                f"{where_sql}"
            )

        column_lines = []
        for col in columns:
            if not isinstance(col, dict):
                continue
            from_col = col.get("source", "")
            to_col = col.get("alias", from_col)
            macro = col.get("macro")
            macro_args = col.get("macro_args")
            expression = col.get("expression")

            if isinstance(expression, str) and expression.strip():
                # The expression item (ADR 0037): verbatim SQL
                # under its alias, carried exactly as written.
                column_lines.append(f"    {expression} AS {to_col}")
            elif macro:
                macro_call = self._build_macro_call(
                    macro, from_col, macro_args, col.get("macro_column_param")
                )
                column_lines.append(f"    {macro_call} AS {to_col}")
            else:
                column_lines.append(f"    {from_col} AS {to_col}")

        columns_sql = ",\n".join(column_lines)
        return (
            f"-- Generated by Loom\n"
            f"-- Source: {source_name}.{table_name}\n"
            "SELECT\n"
            f"{columns_sql},\n"
            f"  {dialect.current_timestamp} AS __loaded_at\n"
            f"FROM {{{{ source('{source_name}', '{table_name}') }}}}"
            f"{where_sql}"
        )

    def _render_inline_source(
        self,
        inline_source: dict,
        columns: list | None,
        dialect: Dialect,
        name: str,
        where_sql: str = "",
    ) -> str:
        source_name = inline_source.get("name")
        schema_name = inline_source.get("schema", "main")
        table_name = inline_source.get("table")
        if not source_name or not table_name:
            raise ValueError(
                f"staging instance {name!r} requires inline_source "
                "'name' and 'table'"
            )

        if not columns:
            return (
                f"-- Generated by Loom\n"
                f"-- Inline source: {source_name}.{schema_name}.{table_name}\n"
                "SELECT *,\n"
                f"  {dialect.current_timestamp} AS __loaded_at\n"
                f"FROM {{{{ source('{source_name}', '{table_name}') }}}}"
                f"{where_sql}"
            )

        column_lines = []
        for col in columns:
            if not isinstance(col, dict):
                continue
            from_col = col.get("source", "")
            to_col = col.get("alias", from_col)
            macro = col.get("macro")
            macro_args = col.get("macro_args")
            expression = col.get("expression")

            if isinstance(expression, str) and expression.strip():
                # The expression item (ADR 0037): verbatim SQL
                # under its alias, carried exactly as written.
                column_lines.append(f"    {expression} AS {to_col}")
            elif macro:
                macro_call = self._build_macro_call(
                    macro, from_col, macro_args, col.get("macro_column_param")
                )
                column_lines.append(f"    {macro_call} AS {to_col}")
            else:
                column_lines.append(f"    {from_col} AS {to_col}")

        columns_sql = ",\n".join(column_lines)
        return (
            f"-- Generated by Loom\n"
            f"-- Inline source: {source_name}.{schema_name}.{table_name}\n"
            "SELECT\n"
            f"{columns_sql},\n"
            f"  {dialect.current_timestamp} AS __loaded_at\n"
            f"FROM {{{{ source('{source_name}', '{table_name}') }}}}"
            f"{where_sql}"
        )

    def _build_macro_call(
        self,
        macro: str,
        col: str,
        macro_args: list | None,
        column_param: int | None = None,
    ) -> str:
        # The macro: slot's calling convention is column-first
        # (position 1). macro_column_param (Tier 2) pins the
        # 1-based position the source column fills among the
        # macro's arguments, for signatures that are not
        # column-first (dbt.date_trunc(datepart, date));
        # macro_args carries the remaining literal arguments in
        # signature order. Assembly is declaration-only - the
        # renderer is manifest-free by design. The invocation is
        # emitted as a plain Jinja expression call: the earlier
        # {% call %} block form is rejected by dbt for ordinary
        # macros ("two values for the special caller argument",
        # verified on dbt 1.12.5), and the slot's macros take
        # the column as a string argument, so the expression
        # form carries the identical convention.
        literals = [repr(argument) for argument in macro_args] if macro_args else []
        if column_param is None:
            position = 1
        elif (
            isinstance(column_param, bool)
            or not isinstance(column_param, int)
            or not 1 <= column_param <= len(literals) + 1
        ):
            raise ValueError(
                f"macro_column_param {column_param!r} cannot place the "
                f"source column among the {len(literals) + 1} argument(s) "
                "the call supplies (the source column plus macro_args)"
            )
        else:
            position = column_param
        parts = literals[: position - 1] + [f"'{col}'"] + literals[position - 1 :]
        return f"{{{{ {macro}({', '.join(parts)}) }}}}"
