from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


_VARIANTS = ("type_2", "type_3", "type_6")


class SCD2Renderer(BaseRenderer):
    """Renderer for the scd2_dimension generator.

    Produces dbt snapshot SQL and a dimension model exposing the full
    history (__valid_from, __valid_to, __is_deleted): open and closed rows,
    including hard-delete tombstones. __is_deleted is normalized to a
    real boolean via the dialect's deleted_flag_template, because
    adapters materialize dbt_is_deleted with inconsistent types.

    Variants (ADR 0031): the snapshot is identical for all
    variants; the dimension model differs. `type_2` (the default)
    exposes the full history as above. `type_3` exposes current
    state plus a `previous_<column>` per `previous_value_columns`
    entry. `type_6` exposes the full history plus a `current_<column>`
    for every tracked column and the Type 3 previous-value columns.
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        input_model = (params.get("input_models") or ["unknown"])[0]
        business_key = params.get("business_key", "unknown")
        tracked_columns = params.get("tracked_columns", [])
        name = params.get("name", "unknown")
        variant = params.get("variant", "type_2")
        if variant not in _VARIANTS:
            raise LoomError(
                f"scd2_dimension variant {variant!r} is not supported; "
                f"expected one of: {', '.join(_VARIANTS)}"
            )
        previous_columns = params.get("previous_value_columns", [])
        if variant in ("type_3", "type_6") and not previous_columns:
            raise LoomError(
                f"scd2_dimension variant {variant!r} requires a non-empty "
                "'previous_value_columns' list"
            )

        # Derive snapshot name: stg_customers -> customers_history
        if name.startswith("stg_"):
            snapshot_name = f"{name[4:]}_history"
        else:
            snapshot_name = f"{name}_history"

        if output_path is None:
            return self._render_snapshot(
                snapshot_name,
                input_model,
                business_key,
                tracked_columns,
                dialect,
                name,
                row_filter=params.get("filter"),
            )
        else:
            return self._render_view(
                input_model,
                business_key,
                tracked_columns,
                dialect,
                name,
                variant,
                previous_columns,
            )

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        business_key = params.get("business_key", "unknown")
        name = params.get("name", "unknown")
        variant = params.get("variant", "type_2")

        # Type 3 holds one current row per business key, so its key
        # is unique outright; the history-exposing variants test
        # uniqueness over current rows only.
        if variant == "type_3":
            unique_block = "          - unique\n"
        else:
            unique_block = (
                "          - unique:\n"
                "              config:\n"
                "                where: __valid_to IS NULL\n"
            )
        tests_yaml = (
            f"# Generated by Loom\n"
            f"version: 2\n"
            f"models:\n"
            f"  - name: {name}\n"
            f"    columns:\n"
            f"      - name: {business_key}\n"
            f"        tests:\n"
            f"          - not_null\n"
            f"{unique_block}"
        )
        return tests_yaml

    def _render_snapshot(
        self,
        snapshot_name: str,
        input_model: str,
        business_key: str,
        tracked_columns: list,
        dialect: Dialect,
        name: str,
        row_filter: object = None,
    ) -> str:
        tracked = (
            ", ".join(repr(col) for col in tracked_columns) if tracked_columns else "[]"
        )

        # The `filter` parameter (ADR 0038): a verbatim predicate
        # on the snapshot's input select - it restricts which
        # input rows enter SCD2 processing at all. It is NOT a
        # filter over the generated history: the dimension views
        # read the snapshot and are unchanged, and a row the
        # predicate excludes never opens a history row. Absent,
        # the snapshot render is unchanged, byte for byte.
        where_sql = (
            f" WHERE {row_filter}"
            if isinstance(row_filter, str) and row_filter.strip()
            else ""
        )

        # Build the snapshot config. hard_deletes is omitted entirely
        # for adapters that reject the property (dbt-clickhouse);
        # their snapshots close deleted rows without a tombstone.
        if tracked_columns:
            check_cols_str = ", ".join(repr(c) for c in tracked_columns)
        else:
            check_cols_str = repr(business_key)
        hard_deletes_line = ""
        if dialect.snapshot_hard_deletes is not None:
            mode = "new_record" if dialect.snapshot_hard_deletes else "fail"
            hard_deletes_line = f",\n        hard_deletes='{mode}'"
        sql = (
            "-- Generated by Loom\n"
            f"-- Generator: scd2_dimension\n"
            f"-- Snapshot: {snapshot_name}\n"
            "{% snapshot " + snapshot_name + " %}\n"
            "    {{ config(\n"
            "        strategy='check',\n"
            f"        unique_key='{business_key}',\n"
            f"        check_cols=[{check_cols_str}]"
            f"{hard_deletes_line}\n"
            "    ) }}\n"
            "    SELECT * FROM {{ ref('" + input_model + "') }}"
            + where_sql
            + "\n"
            "{% endsnapshot %}\n"
        )
        return sql

    def _render_view(
        self,
        input_model: str,
        business_key: str,
        tracked_columns: list,
        dialect: Dialect,
        name: str,
        variant: str = "type_2",
        previous_columns: list | None = None,
    ) -> str:
        if name.startswith("stg_"):
            snapshot_name = f"{name[4:]}_history"
        else:
            snapshot_name = f"{name}_history"

        if variant == "type_3":
            return self._render_view_type3(
                snapshot_name,
                business_key,
                tracked_columns,
                previous_columns or [],
                dialect,
            )
        if variant == "type_6":
            return self._render_view_type6(
                snapshot_name,
                business_key,
                tracked_columns,
                previous_columns or [],
                dialect,
            )

        # The business key heads the column list; tracked columns that
        # repeat it must not select it a second time.
        columns = [business_key] + [
            col for col in tracked_columns if col != business_key
        ]
        column_list = ",\n    ".join(columns)

        # No current-row filter: the dimension exposes full history
        # (closed rows and deletion tombstones included), per the
        # documented SCD2 contract. Consumers who want current state
        # filter on __valid_to IS NULL themselves.
        # Adapters whose snapshots carry no deleted-flag column
        # (dbt-clickhouse) record deletes only as closed rows, so
        # __is_deleted is a constant false there - documented in the
        # architecture's SCD2 section rather than fabricated.
        if dialect.snapshot_deleted_column is not None:
            is_deleted = dialect.deleted_flag_template.format(
                col=dialect.snapshot_deleted_column
            )
        else:
            is_deleted = "FALSE"
        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: scd2_dimension\n"
            f"-- View: full snapshot history\n"
            "SELECT\n"
            f"    {column_list},\n"
            f"    dbt_valid_from AS __valid_from,\n"
            f"    dbt_valid_to AS __valid_to,\n"
            f"    {is_deleted} AS __is_deleted\n"
            f"FROM {{{{ ref('{snapshot_name}') }}}}"
        )
        return sql

    def _is_deleted_expression(self, dialect: Dialect, col: str) -> str:
        if dialect.snapshot_deleted_column is not None:
            return dialect.deleted_flag_template.format(col=col)
        return "FALSE"

    def _render_view_type3(
        self,
        snapshot_name: str,
        business_key: str,
        tracked_columns: list,
        previous_columns: list,
        dialect: Dialect,
    ) -> str:
        tracked = [col for col in tracked_columns if col != business_key]
        deleted_column = dialect.snapshot_deleted_column

        history_parts = [f"        {business_key}"]
        history_parts += [f"        {col}" for col in tracked]
        history_parts += [
            f"        LAG({col}) OVER (PARTITION BY {business_key} "
            f"ORDER BY dbt_valid_from) AS previous_{col}"
            for col in previous_columns
        ]
        history_parts.append("        dbt_valid_from")
        history_parts.append("        dbt_valid_to")
        if deleted_column is not None:
            history_parts.append(f"        {deleted_column}")

        select_parts = [f"    {business_key}"]
        select_parts += [f"    {col}" for col in tracked]
        select_parts += [f"    previous_{col}" for col in previous_columns]
        select_parts.append("    dbt_valid_from AS __valid_from")
        is_deleted = self._is_deleted_expression(
            dialect, deleted_column or "dbt_is_deleted"
        )
        select_parts.append(f"    {is_deleted} AS __is_deleted")

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: scd2_dimension\n"
            f"-- View: current state with previous values (SCD Type 3)\n"
            f"WITH history AS (\n"
            f"    SELECT\n"
            + ",\n".join(history_parts)
            + f"\n    FROM {{{{ ref('{snapshot_name}') }}}}\n"
            f")\n"
            f"SELECT\n"
            + ",\n".join(select_parts)
            + f"\nFROM history\n"
            f"WHERE dbt_valid_to IS NULL"
        )
        return sql

    def _render_view_type6(
        self,
        snapshot_name: str,
        business_key: str,
        tracked_columns: list,
        previous_columns: list,
        dialect: Dialect,
    ) -> str:
        tracked = [col for col in tracked_columns if col != business_key]
        deleted_column = dialect.snapshot_deleted_column

        history_parts = [f"        {business_key}"]
        history_parts += [f"        {col}" for col in tracked]
        history_parts += [
            f"        LAG({col}) OVER (PARTITION BY {business_key} "
            f"ORDER BY dbt_valid_from) AS previous_{col}"
            for col in previous_columns
        ]
        history_parts.append("        dbt_valid_from")
        history_parts.append("        dbt_valid_to")
        if deleted_column is not None:
            history_parts.append(f"        {deleted_column}")

        current_parts = [f"        {business_key}"]
        current_parts += [
            f"        {col} AS current_{col}" for col in tracked
        ]

        select_parts = [f"    h.{business_key}"]
        select_parts += [f"    h.{col}" for col in tracked]
        select_parts += [f"    c.current_{col}" for col in tracked]
        select_parts += [f"    h.previous_{col}" for col in previous_columns]
        select_parts.append("    h.dbt_valid_from AS __valid_from")
        select_parts.append("    h.dbt_valid_to AS __valid_to")
        is_deleted = self._is_deleted_expression(
            dialect, f"h.{deleted_column}" if deleted_column else "dbt_is_deleted"
        )
        select_parts.append(f"    {is_deleted} AS __is_deleted")

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: scd2_dimension\n"
            f"-- View: full snapshot history with current and previous "
            f"values (SCD Type 6)\n"
            f"WITH history AS (\n"
            f"    SELECT\n"
            + ",\n".join(history_parts)
            + f"\n    FROM {{{{ ref('{snapshot_name}') }}}}\n"
            f"),\n"
            f"current_rows AS (\n"
            f"    SELECT\n"
            + ",\n".join(current_parts)
            + f"\n    FROM history\n"
            f"    WHERE dbt_valid_to IS NULL\n"
            f")\n"
            f"SELECT\n"
            + ",\n".join(select_parts)
            + f"\nFROM history h\n"
            f"JOIN current_rows c ON c.{business_key} = h.{business_key}"
        )
        return sql
