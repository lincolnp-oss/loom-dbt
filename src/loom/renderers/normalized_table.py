from __future__ import annotations

from pathlib import Path

from loom.dialects import Dialect
from loom.errors import LoomError
from loom.renderers.base import BaseRenderer


class NormalizedTableRenderer(BaseRenderer):
    """Renderer for the normalized_table generator.

    Produces a 3NF normalized table with entity columns separated
    from attribute columns, plus a __loaded_at provenance column.

    An optional `incremental` block turns the
    table incremental with a key strategy (`merge` /
    `delete+insert`): the key defaults to the first entity column -
    the column the generator already treats as the entity key - and
    a declared `cursor_column` adds the shared core's cursor window
    as a scan filter. `append` is not admitted for this generator
    (the inventory validators reject it by name).
    """

    def render(self, params: dict, dialect: Dialect, output_path: Path | None) -> str:
        name = params.get("name", "unknown")
        input_model = (params.get("input_models") or ["unknown"])[0]
        entity_columns = params.get("entity_columns", [])
        attribute_columns = params.get("attribute_columns", [])

        # Build SELECT clause
        select_parts: list[str] = []
        for col in entity_columns:
            select_parts.append(f"  {col}")
        for col in attribute_columns:
            select_parts.append(f"  {col}")
        select_parts.append(f"  {dialect.current_timestamp} AS __loaded_at")

        select_sql = ",\n".join(select_parts)

        default_key = (entity_columns[0],) if entity_columns else ()
        spec = self._incremental_spec(params, default_key=default_key)
        config = "{{ config(materialized='table') }}"
        # The `filter` parameter (ADR 0038): a verbatim predicate
        # opening the WHERE over the input scan. With an
        # incremental cursor it composes as a single WHERE -
        # filter first, cursor predicate ANDed behind it inside
        # its gate (see the prepend after the spec block). Absent,
        # the render is unchanged, byte for byte.
        row_filter = params.get("filter")
        filter_present = isinstance(row_filter, str) and bool(row_filter.strip())
        filter_sql = ""
        if spec is not None:
            self._check_incremental_strategy(spec, dialect, model_name=name)
            if spec.strategy == "append":
                raise LoomError(
                    f"normalized_table {name!r}: incremental strategy "
                    "'append' is not supported for normalized_table; "
                    "use 'merge' or 'delete+insert' (design §3.5 admits "
                    "key strategies only)"
                )
            if not spec.unique_key:
                raise LoomError(
                    f"normalized_table {name!r}: incremental strategy "
                    f"{spec.strategy!r} requires a unique key - declare "
                    "'unique_key' or at least one entity column to "
                    "default it from"
                )
            config = self._incremental_config(spec)
            if spec.cursor_column is not None:
                filter_sql = self._cursor_predicate(
                    spec, conjunction=filter_present
                )

        if filter_present:
            filter_sql = f"\nWHERE {row_filter}" + filter_sql

        sql = (
            f"-- Generated by Loom\n"
            f"-- Generator: normalized_table\n"
            f"-- Paradigm: threenf\n"
            f"{config}\n"
            f"SELECT\n"
            f"{select_sql}\n"
            f"FROM {{{{ ref('{input_model}') }}}}"
            f"{filter_sql}"
        )
        return sql

    def render_tests(
        self, params: dict, dialect: Dialect, output_path: Path | None
    ) -> str | None:
        """Generate tests for entity columns.

        Every entity column is checked for not_null. The FIRST
        entity column is the entity key and additionally carries a
        unique test: a normalized table's identity contract,
        enforced as a generated data test -
        deliberately not SQL deduplication, which would silently
        discard rows instead of failing the build.
        """
        entity_columns = params.get("entity_columns", [])
        name = params.get("name", "unknown")
        if not entity_columns:
            return None
        col_lines = []
        for index, col in enumerate(entity_columns):
            col_lines.append(f"      - name: {col}")
            col_lines.append(f"        tests:")
            col_lines.append(f"          - not_null")
            if index == 0:
                col_lines.append(f"          - unique")
        tests_yaml = (
            "# Generated by Loom\nversion: 2\nmodels:\n"
            f"  - name: {name}\n    columns:\n"
            + "\n".join(col_lines) + "\n"
        )
        return tests_yaml
