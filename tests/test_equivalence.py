"""The static equivalence stage (strict form):
per-model proven/inconclusive verdicts over two compiled
manifests, under the pinned normalisation set and proof
conditions C1–C8. The stage only ever proves or abstains."""
from __future__ import annotations

import json
from pathlib import Path

import pytest

from loom.equivalence import _tokens, static_stage_report
from loom.errors import LoomError


def _node(
    name: str,
    sql: str | None,
    columns: list[str],
    *,
    resource_type: str = "model",
    materialized: str = "view",
) -> dict:
    return {
        "name": name,
        "resource_type": resource_type,
        "package_name": "proj",
        "compiled_code": sql,
        "columns": {column: {} for column in columns},
        "config": {"materialized": materialized},
    }


def _manifest(nodes: dict, adapter: str = "duckdb") -> dict:
    return {
        "metadata": {
            "project_name": "proj",
            "adapter_type": adapter,
            "generated_at": "2026-01-01T00:00:00+00:00",
        },
        "nodes": nodes,
    }


def _report(tmp_path: Path, original: dict, candidate: dict) -> dict:
    directory = tmp_path / "local" / "equivalence"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "original.manifest.json").write_text(
        json.dumps(original), encoding="utf-8"
    )
    (directory / "candidate.manifest.json").write_text(
        json.dumps(candidate), encoding="utf-8"
    )
    return static_stage_report(tmp_path)


def _verdict(report: dict, name: str = "stg_events") -> dict:
    return next(m for m in report["models"] if m["name"] == name)


_ORIGINAL_SQL = "select id, name from raw.events"
_STG_COLUMNS = ["id", "name"]


def _pair(
    tmp_path: Path,
    original_sql: str | None = _ORIGINAL_SQL,
    candidate_sql: str | None = _ORIGINAL_SQL,
    original_columns: list[str] = _STG_COLUMNS,
    candidate_columns: list[str] = _STG_COLUMNS,
    **candidate_kwargs,
) -> dict:
    original = _manifest(
        {"model.proj.stg_events": _node("stg_events", original_sql, original_columns)}
    )
    candidate = _manifest(
        {
            "model.proj.stg_events": _node(
                "stg_events", candidate_sql, candidate_columns, **candidate_kwargs
            )
        }
    )
    return _report(tmp_path, original, candidate)


# --- the normalisation set -------------------------------------------


def test_tokens_collapse_layout_case_and_comments() -> None:
    assert _tokens("SELECT  id,\n  name -- pick both\nFROM t;") == _tokens(
        "select id, name from t"
    )


def test_tokens_preserve_string_literals_and_quoted_identifiers() -> None:
    assert _tokens("select 'Day' , \"Name\" from t") != _tokens(
        "select 'day' , \"name\" from t"
    )
    assert _tokens("select 'a  b' from t") != _tokens("select 'a b' from t")


def test_proven_despite_formatting_and_generated_header(tmp_path: Path) -> None:
    report = _pair(
        tmp_path,
        candidate_sql=(
            "-- Generated by Loom\nSELECT\n    id,\n    name\nFROM raw.events\n"
        ),
    )
    assert _verdict(report)["verdict"] == "proven"


def test_inconclusive_on_expression_difference(tmp_path: Path) -> None:
    report = _pair(
        tmp_path, candidate_sql="select id, upper(name) from raw.events"
    )
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    assert "differs after normalisation" in verdict["basis"]


def test_inconclusive_on_select_item_order(tmp_path: Path) -> None:
    # Select-item order is decisive in the strict set (OUT list).
    report = _pair(tmp_path, candidate_sql="select name, id from raw.events")
    assert _verdict(report)["verdict"] == "inconclusive"


def test_inconclusive_on_alias_difference(tmp_path: Path) -> None:
    report = _pair(
        tmp_path, candidate_sql="select id, name as label from raw.events"
    )
    assert _verdict(report)["verdict"] == "inconclusive"


# --- the __ declared-difference rule ---------------------------------


def test_proven_with_candidate_only_dunder_column(tmp_path: Path) -> None:
    # The generated staging shape: an audit item the original
    # lacks, excluded whole - including its run-varying
    # expression, which therefore cannot false-abstain (C6 runs
    # after the exclusion).
    report = _pair(
        tmp_path,
        candidate_sql=(
            "select id, name, localtimestamp as __loaded_at from raw.events"
        ),
        candidate_columns=["id", "name", "__loaded_at"],
    )
    assert _verdict(report)["verdict"] == "proven"


def test_inconclusive_when_candidate_adds_a_real_column(tmp_path: Path) -> None:
    report = _pair(
        tmp_path,
        candidate_sql="select id, name, extra from raw.events",
        candidate_columns=["id", "name", "extra"],
    )
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    # B-2: the basis names the fact in documentation terms - the
    # column may be the original's own, undocumented - instead
    # of blaming the candidate for adding it.
    assert "no documented counterpart: candidate column 'extra'" in verdict["basis"]
    assert "documentation may be incomplete" in verdict["basis"]
    assert report["documentation_partial"] == ["stg_events"]


def test_documentation_partial_lists_undocumented_originals(
    tmp_path: Path,
) -> None:
    # An original documenting no columns at all is partial by
    # the same measure, whatever its verdict.
    report = _pair(tmp_path, original_columns=[], candidate_columns=[])
    assert report["documentation_partial"] == ["stg_events"]


def test_documentation_partial_empty_when_documentation_complete(
    tmp_path: Path,
) -> None:
    report = _pair(tmp_path)
    assert report["documentation_partial"] == []


def test_dunder_item_inside_a_cte_is_not_excluded(tmp_path: Path) -> None:
    # The exclusion applies to the FINAL select list only: the
    # CTE's __ item stays in the text, so the comparison differs
    # and abstains (the safe direction).
    report = _pair(
        tmp_path,
        candidate_sql=(
            "with x as (select id, name, 1 as __loaded_at from raw.events) "
            "select id, name from x"
        ),
        candidate_columns=["id", "name", "__loaded_at"],
    )
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    assert "differs after normalisation" in verdict["basis"]


def test_proven_when_dunder_column_is_undocumented_in_candidate(
    tmp_path: Path,
) -> None:
    # Harness-found (jaffle): a generated model's __loaded_at is
    # routinely NOT among the candidate manifest's documented
    # columns (the playbook keeps the project's own schema YAML
    # and deletes the generated properties document). The
    # exclusion reads the select list, not the documented
    # columns, so the proof still lands.
    report = _pair(
        tmp_path,
        candidate_sql=(
            "select id, name, localtimestamp as __loaded_at from raw.events"
        ),
        candidate_columns=["id", "name"],
    )
    assert _verdict(report)["verdict"] == "proven"


# --- the proof conditions --------------------------------------------


def test_inconclusive_when_original_column_has_no_counterpart(
    tmp_path: Path,
) -> None:
    report = _pair(tmp_path, candidate_columns=["id"])
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    assert "original column 'name' has no candidate counterpart" in verdict["basis"]


def test_inconclusive_when_absent_from_candidate(tmp_path: Path) -> None:
    original = _manifest(
        {"model.proj.stg_events": _node("stg_events", _ORIGINAL_SQL, _STG_COLUMNS)}
    )
    report = _report(tmp_path, original, _manifest({}))
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    assert "absent from the candidate manifest" in verdict["basis"]


def test_inconclusive_for_incremental_and_snapshot(tmp_path: Path) -> None:
    report = _pair(tmp_path, materialized="incremental")
    assert "stateful" in _verdict(report)["basis"]
    report = _pair(tmp_path, resource_type="snapshot")
    assert "stateful" in _verdict(report)["basis"]


def test_inconclusive_without_compiled_code(tmp_path: Path) -> None:
    report = _pair(tmp_path, candidate_sql=None)
    assert "no compiled code" in _verdict(report)["basis"]


def test_inconclusive_with_unresolved_jinja(tmp_path: Path) -> None:
    report = _pair(
        tmp_path, candidate_sql="select id, name from {{ ref('events') }}"
    )
    assert "unresolved Jinja" in _verdict(report)["basis"]


def test_inconclusive_with_run_varying_value_in_original(tmp_path: Path) -> None:
    report = _pair(
        tmp_path,
        original_sql=(
            "select id, name from raw.events where loaded_at < current_timestamp"
        ),
        candidate_sql=(
            "select id, name from raw.events where loaded_at < current_timestamp"
        ),
    )
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    assert "run-varying value" in verdict["basis"]


def test_adapter_mismatch_abstains_stage_wide(tmp_path: Path) -> None:
    original = _manifest(
        {"model.proj.stg_events": _node("stg_events", _ORIGINAL_SQL, _STG_COLUMNS)}
    )
    candidate = _manifest(
        {"model.proj.stg_events": _node("stg_events", _ORIGINAL_SQL, _STG_COLUMNS)},
        adapter="postgres",
    )
    report = _report(tmp_path, original, candidate)
    verdict = _verdict(report)
    assert verdict["verdict"] == "inconclusive"
    assert "adapter mismatch" in verdict["basis"]


def test_candidate_only_models_are_non_subjects(tmp_path: Path) -> None:
    original = _manifest(
        {"model.proj.stg_events": _node("stg_events", _ORIGINAL_SQL, _STG_COLUMNS)}
    )
    candidate = _manifest(
        {
            "model.proj.stg_events": _node(
                "stg_events", _ORIGINAL_SQL, _STG_COLUMNS
            ),
            "model.proj.hub_customer": _node(
                "hub_customer", "select 1", ["customer_hk"]
            ),
        }
    )
    report = _report(tmp_path, original, candidate)
    assert report["non_subjects"] == ["hub_customer"]
    assert report["summary"] == {"subjects": 1, "proven": 1, "inconclusive": 0}


# --- stage states ------------------------------------------------------


def test_stage_not_run_without_manifests(tmp_path: Path) -> None:
    report = static_stage_report(tmp_path)
    assert report["stage"] == "not_run"
    assert report["missing"] == [
        "local/equivalence/original.manifest.json",
        "local/equivalence/candidate.manifest.json",
    ]


def test_stage_not_run_with_one_manifest(tmp_path: Path) -> None:
    directory = tmp_path / "local" / "equivalence"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "original.manifest.json").write_text(
        json.dumps(_manifest({})), encoding="utf-8"
    )
    report = static_stage_report(tmp_path)
    assert report["stage"] == "not_run"
    assert report["missing"] == ["local/equivalence/candidate.manifest.json"]


def test_malformed_manifest_is_an_error(tmp_path: Path) -> None:
    directory = tmp_path / "local" / "equivalence"
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "original.manifest.json").write_text("{nope", encoding="utf-8")
    (directory / "candidate.manifest.json").write_text(
        json.dumps(_manifest({})), encoding="utf-8"
    )
    with pytest.raises(LoomError, match="cannot read the manifest"):
        static_stage_report(tmp_path)
