"""`loom generate` publishes model properties (catalogue).

Runs against the real quickstart. dbt rejects a model described by
two schema files, so each generated model has exactly one Loom
schema document under `_generated/tests/`: properties merge into
`data_<model>.yml` when the generator emits data tests, and a
properties-only `properties_<model>.yml` sits beside it otherwise.
Both shapes are covered by `generate --check` drift detection.
"""
from __future__ import annotations

import shutil
from pathlib import Path

import pytest
import yaml

from loom.cli import main

ROOT = Path(__file__).parents[1]
QUICKSTART = ROOT / "examples" / "quickstart"


def _project(tmp_path: Path) -> Path:
    project = tmp_path / "quickstart"
    shutil.copytree(
        QUICKSTART,
        project,
        ignore=shutil.ignore_patterns("target", "*.duckdb"),
    )
    return project


def _generate(project: Path, *extra: str) -> int:
    return main(
        ["generate", "--write", "--project-dir", str(project), "--dialect", "duckdb", *extra]
    )


def _load_schema(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    assert text.startswith("# Generated by Loom\n")
    return yaml.safe_load(text)


def test_generate_merges_properties_into_data_documents(tmp_path: Path) -> None:
    project = _project(tmp_path)
    assert _generate(project) == 0
    tests_root = project / "models" / "_generated/tests"

    dim = _load_schema(tests_root / "kimball" / "data_dim_customers.yml")
    (model,) = dim["models"]
    assert model["name"] == "dim_customers"
    assert model["description"]
    columns = {c["name"]: c for c in model["columns"]}
    assert list(columns) == [
        "customer_sk",
        "customer_id",
        "customer_hk",
        "__loaded_at",
    ]
    assert columns["customer_sk"]["data_type"] == "BIGINT"
    assert columns["__loaded_at"]["data_type"] == "TIMESTAMP"
    assert "data_type" not in columns["customer_hk"]
    # The data tests survive the merge, on their columns.
    assert columns["customer_id"]["tests"] == ["not_null", "unique"]
    assert columns["customer_sk"]["tests"] == ["unique"]

    hub = _load_schema(tests_root / "vault" / "data_hub_customer.yml")
    hub_model = hub["models"][0]
    assert hub_model["description"]
    hub_columns = {c["name"]: c for c in hub_model["columns"]}
    # The quickstart hub declares no record_source: no audit columns
    # are catalogued (via the general resolver).
    assert list(hub_columns) == ["customer_hk", "customer_id"]
    assert hub_columns["customer_hk"]["data_type"] == "VARCHAR"
    assert hub_columns["customer_hk"]["tests"] == ["unique", "not_null"]
    assert "tests" not in hub_columns["customer_id"]

    link = _load_schema(tests_root / "vault" / "data_link_order_customer.yml")
    link_columns = {c["name"]: c for c in link["models"][0]["columns"]}
    assert list(link_columns) == ["order_customer_hk", "order_hk", "customer_hk"]
    assert all(c["data_type"] == "VARCHAR" for c in link_columns.values())
    assert link_columns["order_customer_hk"]["tests"] == ["unique", "not_null"]


def test_generate_properties_only_documents(tmp_path: Path) -> None:
    project = _project(tmp_path)
    assert _generate(project) == 0
    tests_root = project / "models" / "_generated/tests"

    # Staging emits no data tests: a properties-only document.
    staging = _load_schema(tests_root / "properties_stg_customers.yml")
    staging_columns = [c["name"] for c in staging["models"][0]["columns"]]
    assert staging_columns[-1] == "__loaded_at"

    # Bronze: SELECT * - description only, no invented columns.
    bronze = _load_schema(tests_root / "properties_bronze_customers.yml")
    (bronze_model,) = bronze["models"]
    assert bronze_model["description"]
    assert "columns" not in bronze_model

    # Silver over bronze declares its projection columns:
    # the merged document carries the description, the declared
    # columns plus the carried stamp, and the dedup key's tests.
    silver = _load_schema(tests_root / "data_silver_customers.yml")
    (silver_model,) = silver["models"]
    assert silver_model["description"]
    assert [c["name"] for c in silver_model["columns"]] == [
        "id",
        "customer_name",
        "customer_email",
        "__loaded_at",
    ]
    assert silver_model["columns"][0]["tests"] == ["not_null", "unique"]


def test_schema_documents_are_drift_checked(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _project(tmp_path)
    assert _generate(project) == 0
    capsys.readouterr()
    assert _generate(project, "--check") == 0

    target = (
        project
        / "models"
        / "_generated/tests"
        / "kimball"
        / "data_dim_customers.yml"
    )
    target.write_text(
        target.read_text(encoding="utf-8") + "# hand edit\n", encoding="utf-8"
    )
    capsys.readouterr()
    assert _generate(project, "--check") == 1
    captured = capsys.readouterr()
    assert "data_dim_customers.yml" in (captured.out + captured.err)


def _set_optout(project: Path, instances_file: str, model: str, value=True) -> None:
    path = project / "metadata" / "instances" / instances_file
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    for instance in document["instances"]:
        if instance["name"] == model:
            instance.setdefault("params", {})[
                "skip_properties_document"
            ] = value
    path.write_text(yaml.safe_dump(document), encoding="utf-8")


def test_generate_skips_properties_only_document_on_optout(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _project(tmp_path)
    _set_optout(project, "staging.yml", "stg_customers")
    assert _generate(project) == 0
    out = capsys.readouterr().out
    tests_root = project / "models" / "_generated/tests"
    # The opted-out model's document is not emitted; its SQL is,
    # and other models' documents are unaffected.
    assert not (tests_root / "properties_stg_customers.yml").exists()
    assert (tests_root / "properties_bronze_customers.yml").exists()
    assert (project / "models/_generated/staging/stg_customers.sql").exists()
    assert "Properties documents skipped (1): stg_customers" in out
    assert "skip_properties_document" in out


def test_generate_skips_merged_document_on_optout(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _project(tmp_path)
    _set_optout(project, "dimensions.yml", "dim_customers")
    assert _generate(project) == 0
    out = capsys.readouterr().out
    tests_root = project / "models" / "_generated/tests"
    # dim_customers' generator emits data tests, so the properties
    # entry's vehicle is the merged document: the whole document
    # is skipped (properties entry and generated data tests).
    assert not (tests_root / "kimball" / "data_dim_customers.yml").exists()
    assert "Merged data-test documents skipped (1): dim_customers" in out


def test_generate_check_reports_leftover_properties_document(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _project(tmp_path)
    assert _generate(project) == 0
    leftover = (
        project / "models/_generated/tests/properties_stg_customers.yml"
    )
    assert leftover.exists()
    _set_optout(project, "staging.yml", "stg_customers")
    # --check: the leftover competes with practitioner YAML until
    # removed, so it is drift (stale), never silently ignored.
    assert _generate(project, "--check") == 1
    out = capsys.readouterr().out
    assert "stale:" in out and "properties_stg_customers.yml" in out
    # A write run names it as left in place; it is never deleted.
    assert _generate(project) == 0
    out = capsys.readouterr().out
    assert "left in place:" in out and "properties_stg_customers.yml" in out
    assert leftover.exists()


def test_skip_properties_document_must_be_boolean(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _project(tmp_path)
    _set_optout(project, "staging.yml", "stg_customers", value="yes")
    rc = main(["validate", "--project-dir", str(project)])
    assert rc == 1
    assert (
        "'skip_properties_document' must be true or false"
        in capsys.readouterr().err
    )


def _optout_check_project(tmp_path: Path, *, described: bool) -> Path:
    """A one-model project whose only generated model declares
    the properties opt-out, plus a freshness-valid manifest."""
    import json

    project = tmp_path / "mini"
    (project / "metadata" / "patterns").mkdir(parents=True)
    (project / "metadata" / "instances").mkdir(parents=True)
    (project / "models" / "_generated" / "staging").mkdir(parents=True)
    (project / "target").mkdir()
    (project / "dbt_project.yml").write_text("name: mini\n", encoding="utf-8")
    shutil.copy(
        QUICKSTART / "metadata" / "patterns" / "staging.yml",
        project / "metadata" / "patterns" / "staging.yml",
    )
    (project / "metadata" / "instances" / "staging.yml").write_text(
        "format_version: '1.0'\n"
        "pattern: staging\n"
        "instances:\n"
        "  - name: stg_customers\n"
        "    params:\n"
        "      description: Customer staging.\n"
        "      skip_properties_document: true\n"
        "      source_ref: {name: raw, table: customers}\n"
        "      columns:\n"
        "        - {source: id, alias: customer_id}\n",
        encoding="utf-8",
    )
    (project / "models" / "sources.yml").write_text(
        "version: 2\n"
        "sources:\n"
        "  - name: raw\n"
        "    tables:\n"
        "      - name: customers\n",
        encoding="utf-8",
    )
    sql = "select id as customer_id from raw.customers\n"
    model_file = project / "models/_generated/staging/stg_customers.sql"
    model_file.write_text(sql, encoding="utf-8")
    node = {
        "resource_type": "model",
        "package_name": "mini",
        "name": "stg_customers",
        "original_file_path": "models/_generated/staging/stg_customers.sql",
        "raw_code": sql,
        "depends_on": {"nodes": []},
        "columns": {},
        "config": {"materialized": "view"},
    }
    if described:
        node["description"] = "Customers, described by the practitioner."
    document = {
        "metadata": {
            "project_name": "mini",
            "generated_at": "2999-01-01T00:00:00+00:00",
        },
        "nodes": {"model.mini.stg_customers": node},
        "sources": {},
    }
    (project / "target" / "manifest.json").write_text(
        json.dumps(document), encoding="utf-8"
    )
    return project


def test_check_warns_when_opted_out_model_has_no_description(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _optout_check_project(tmp_path, described=False)
    rc = main(["check", "--project-dir", str(project)])
    assert rc == 0
    captured = capsys.readouterr()
    assert "Inventory coverage is current." in captured.out
    # The safety net: opting out and never writing the YAML must
    # not be silent.
    assert "declares skip_properties_document" in captured.err
    assert "no practitioner description" in captured.err


def test_check_silent_when_opted_out_model_is_described(
    tmp_path: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    project = _optout_check_project(tmp_path, described=True)
    rc = main(["check", "--project-dir", str(project)])
    assert rc == 0
    assert "skip_properties_document" not in capsys.readouterr().err


def _set_generic_tests(
    project: Path, instances_file: str, model: str, tests: list
) -> None:
    path = project / "metadata" / "instances" / instances_file
    document = yaml.safe_load(path.read_text(encoding="utf-8"))
    for instance in document["instances"]:
        if instance["name"] == model:
            instance.setdefault("params", {})["generic_tests"] = tests
    path.write_text(yaml.safe_dump(document), encoding="utf-8")


def test_generate_carries_generic_tests_into_properties_document(
    tmp_path: Path,
) -> None:
    # Carriage on a generator that emits no data tests
    # (staging): the declarations land in the properties
    # document - column tests on their columns, kwargs in the
    # mapping form, model-level tests on the model entry.
    project = _project(tmp_path)
    _set_generic_tests(
        project,
        "staging.yml",
        "stg_customers",
        [
            {"test": "not_null", "column_name": "customer_id"},
            {"test": "unique", "column_name": "customer_id"},
            {
                "test": "dbt_utils.expression_is_true",
                "column_name": "customer_name",
                "kwargs": {"expression": "customer_name <> ''"},
            },
            {"test": "custom_model_check"},
        ],
    )
    assert _generate(project) == 0
    document = _load_schema(
        project / "models/_generated/tests/properties_stg_customers.yml"
    )
    (model,) = document["models"]
    assert model["tests"] == ["custom_model_check"]
    columns = {c["name"]: c for c in model["columns"]}
    assert columns["customer_id"]["tests"] == ["not_null", "unique"]
    assert columns["customer_name"]["tests"] == [
        {"dbt_utils.expression_is_true": {"expression": "customer_name <> ''"}}
    ]


def test_generate_carries_generic_tests_into_merged_document(
    tmp_path: Path,
) -> None:
    # On a generator that emits data tests (hub), carriage
    # merges into the same single document - and a carried
    # declaration that duplicates a generator-emitted test
    # (same name, column and kwargs) is emitted once, not
    # twice: dbt names the test from those three and rejects
    # the duplicate at parse. (This reverses the earlier
    # emit-both stance; `loom check` still warns about the
    # redundant declaration.)
    project = _project(tmp_path)
    _set_generic_tests(
        project,
        "hubs.yml",
        "hub_customer",
        [
            {"test": "not_null", "column_name": "customer_id"},
            {"test": "unique", "column_name": "customer_hk"},
        ],
    )
    assert _generate(project) == 0
    document = _load_schema(
        project / "models/_generated/tests/vault/data_hub_customer.yml"
    )
    model = document["models"][0]
    columns = {c["name"]: c for c in model["columns"]}
    assert columns["customer_id"]["tests"] == ["not_null"]
    assert columns["customer_hk"]["tests"] == ["unique", "not_null"]
