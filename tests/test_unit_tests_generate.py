ROOT = Path(__file__).parents[1]
QUICKSTART = ROOT / "examples" / "quickstart"

DIM_TESTS = [
    {
        "name": "dim_customers__surrogate_keys_follow_natural_key_order",
        "description": "Surrogate keys follow natural-key order.",
        "given": [
            {
                "input": "hub_customer",
                "rows": [
                    {"customer_id": 2, "customer_hk": "h2"},
                    {"customer_id": 1, "customer_hk": "h1"},
                ],
            }
        ],
        "expect": {
            "rows": [
                {"customer_sk": 1, "customer_id": 1, "customer_hk": "h1"},
                {"customer_sk": 2, "customer_id": 2, "customer_hk": "h2"},
            ]
        },
    }
]


def _quickstart_copy(tmp_path: Path, with_tests: bool = False) -> Path:
    project = tmp_path / "quickstart"
    shutil.copytree(QUICKSTART, project)
    if with_tests:
        instances_path = project / "metadata" / "instances" / "dimensions.yml"
        document = yaml.safe_load(instances_path.read_text(encoding="utf-8"))
        for instance in document["instances"]:
            if instance["name"] == "dim_customers":
                instance["params"]["unit_tests"] = DIM_TESTS
        instances_path.write_text(
            yaml.safe_dump(document, sort_keys=False), encoding="utf-8"
        )
    return project


def _generate(project: Path, capsys) -> tuple[int, str, str]:
    rc = main(["generate", "--write", "--project-dir", str(project)])
    captured = capsys.readouterr()
    return rc, captured.out, captured.err


def test_generate_emits_unit_test_document(tmp_path, capsys) -> None:
    project = _quickstart_copy(tmp_path, with_tests=True)
    rc, out, _err = _generate(project, capsys)
    assert rc == 0
    # The counts lead; the per-file detail is behind
    # --verbose, where the unit-test name appears.
    assert "1 unit-test file" in out
    assert "dim_customers__surrogate_keys_follow_natural_key_order" not in out
    rc = main(["generate", "--write", "--project-dir", str(project), "--verbose"])
    out = capsys.readouterr().out
    assert rc == 0
    assert "Unit-test files (1):" in out
    assert "dim_customers__surrogate_keys_follow_natural_key_order" in out

    unit_path = (
        project / "models" / "_generated/tests" / "kimball" / "unit_dim_customers.yml"
    )
    text = unit_path.read_text(encoding="utf-8")
    assert text.startswith("# Generated by Loom\n")
    document = yaml.safe_load(text)
    assert document["version"] == 2
    (test,) = document["unit_tests"]
    assert test["name"] == "dim_customers__surrogate_keys_follow_natural_key_order"
    assert test["model"] == "dim_customers"
    assert test["given"][0]["input"] == "ref('hub_customer')"
    assert test["given"][0]["rows"][0] == {"customer_id": 2, "customer_hk": "h2"}
    assert test["expect"]["rows"][1] == {
        "customer_sk": 2,
        "customer_id": 2,
        "customer_hk": "h2",
    }


