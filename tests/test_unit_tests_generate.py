def _handwritten_project(tmp_path, *, documented: bool = True):
    """A project with hand-written models only: no Loom metadata,
    a manifest documenting the models, their columns and deps."""
    project = tmp_path / "hw"
    (project / "models").mkdir(parents=True)
    (project / "target").mkdir()
    (project / "dbt_project.yml").write_text(
        "name: hw_project\n", encoding="utf-8"
    )
    (project / "models" / "stg_orders.sql").write_text(
        "select 1\n", encoding="utf-8"
    )
    (project / "models" / "orders.sql").write_text(
        "select 1\n", encoding="utf-8"
    )
    cols = (
        lambda names: {name: {} for name in names} if documented else {}
    )
    document = {
        "metadata": {
            "project_name": "hw_project",
            "generated_at": "2999-01-01T00:00:00+00:00",
        },
        "nodes": {
            "model.hw_project.stg_orders": {
                "resource_type": "model",
                "package_name": "hw_project",
                "name": "stg_orders",
                "original_file_path": "models/stg_orders.sql",
                "raw_code": "select 1\n",
                "depends_on": {"nodes": []},
                "columns": cols(["order_id", "sku"]),
            },
            "model.hw_project.orders": {
                "resource_type": "model",
                "package_name": "hw_project",
                "name": "orders",
                "original_file_path": "models/orders.sql",
                "raw_code": "select 1\n",
                "depends_on": {
                    "nodes": [
                        "model.hw_project.stg_orders",
                        "source.hw_project.raw.events",
                    ]
                },
                "columns": cols(["order_id", "total"]),
            },
        },
        "sources": {
            "source.hw_project.raw.events": {
                "source_name": "raw",
                "name": "events",
                "columns": cols(["event_id"]),
            }
        },
    }
    (project / "target" / "manifest.json").write_text(
        json.dumps(document), encoding="utf-8"
    )
    return project


def test_create_new_handwritten_model_prints_dbt_yaml(tmp_path, capsys) -> None:
    project = _handwritten_project(tmp_path)
    rc = main(
        ["create-new", "unit-test", "orders", "--project-dir", str(project)]
    )
    assert rc == 0
    out = capsys.readouterr().out
    assert out.startswith("unit_tests:\n")
    assert "orders__todo_scenario" in out
    assert "    model: orders" in out
    # given inputs derive from the manifest's depends_on: models
    # as ref('…'), sources as source('…', '…'), each with a
    # sentinel row keyed by the input's documented columns.
    assert "- input: ref('stg_orders')" in out
    assert '{order_id: "__TODO__", sku: "__TODO__"}' in out
    assert "- input: source('raw', 'events')" in out
    assert '{event_id: "__TODO__"}' in out
    # expect rows keyed by the model's documented columns.
    assert '{order_id: "__TODO__", total: "__TODO__"}' in out


