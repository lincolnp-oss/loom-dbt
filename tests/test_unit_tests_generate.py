def _assert_no_duplicate_keys(text: str) -> None:
    """Every mapping in the parsed document carries each key once
    (PyYAML's safe_load silently keeps the last duplicate, so the
    node tree is inspected directly)."""
    def walk(node) -> None:
        if isinstance(node, yaml.MappingNode):
            keys = [key.value for key, _value in node.value]
            assert len(keys) == len(set(keys)), f"duplicate keys: {keys}"
            for _key, value in node.value:
                walk(value)
        elif isinstance(node, yaml.SequenceNode):
            for item in node.value:
                walk(item)
    walk(yaml.compose(text))


def test_create_new_staging_scaffold_dedupes_shared_source_column(
    tmp_path, capsys
) -> None:
    # QOL D-3 repro (Pass D's stg_coupons shape): one source column
    # feeds both a plain mapping and a macro mapping. The scaffold
    # used to key the given row with that column twice (a duplicate
    # YAML key) and to emit a second given block for the same input
    # claiming its columns could not be derived.
    project = _quickstart_copy(tmp_path)
    instances_path = project / "metadata" / "instances" / "staging.yml"
    document = yaml.safe_load(instances_path.read_text(encoding="utf-8"))
    for instance in document["instances"]:
        if instance["name"] == "stg_customers":
            instance["params"]["columns"].append(
                {
                    "source": "customer_name",
                    "alias": "customer_name_shouted",
                    "macro": "shout",
                }
            )
    instances_path.write_text(
        yaml.safe_dump(document, sort_keys=False), encoding="utf-8"
    )
    macros_dir = project / "macros"
    macros_dir.mkdir(exist_ok=True)
    (macros_dir / "shout.sql").write_text(
        "{% macro shout(column_name) %}upper({{ column_name }}){% endmacro %}\n",
        encoding="utf-8",
    )
    rc = main(
        ["create-new", "unit-test", "stg_customers", "--project-dir", str(project)]
    )
    assert rc == 0
    out = capsys.readouterr().out
    _assert_no_duplicate_keys(out)
    parsed = yaml.safe_load(out)
    given = parsed["unit_tests"][0]["given"]
    assert len(given) == 1  # one given block for the one input
    assert given[0]["input"] == "customers"
    row = given[0]["rows"][0]
    assert list(row) == ["id", "customer_name", "customer_email"]
    assert "could not be derived" not in out


