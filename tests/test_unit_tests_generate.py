def _emit_project(tmp_path: Path) -> Path:
    """A small project declaring unit tests on staging, bronze
    and a satellite (the three generators the 2026-11-04 ruling
    extended coverage to), generated in place."""
    (tmp_path / "dbt_project.yml").write_text(
        "name: emit_proof\nversion: '1.0'\nconfig-version: 2\nprofile: emit_proof\n",
        encoding="utf-8",
    )
    write_pattern_instance(
        tmp_path,
        "stg_widgets",
        "staging",
        {
            "description": "Widget staging",
            "owner": "analytics",
            "inline_source": {"name": "raw", "schema": "main", "table": "widgets"},
            "columns": [
                {"source": "widget_id", "alias": "widget_id"},
                {"source": "widget_name", "alias": "widget_name"},
            ],
            "unit_tests": [
                {
                    "name": "stg_widgets__rows_pass_through",
                    "given": [
                        {
                            "input": "widgets",
                            "rows": [{"widget_id": 1, "widget_name": "alpha"}],
                        }
                    ],
                    "expect": {"rows": [{"widget_id": 1, "widget_name": "alpha"}]},
                }
            ],
        },
        pattern="staging",
    )
    write_pattern_instance(
        tmp_path,
        "bronze_gadgets",
        "bronze",
        {
            "description": "Gadgets as landed",
            "owner": "analytics",
            "inline_source": {"name": "raw", "table": "gadgets"},
            "unit_tests": [
                {
                    "name": "bronze_gadgets__rows_land",
                    "given": [{"input": "gadgets", "rows": [{"gadget_id": 1}]}],
                    "expect": {"rows": [{"gadget_id": 1}]},
                }
            ],
        },
        pattern="bronze",
    )
    write_pattern_instance(
        tmp_path,
        "hub_widget",
        "hub",
        {
            "description": "Widget hub",
            "owner": "analytics",
            "input_models": ["stg_widgets"],
            "business_key": "widget_id",
        },
        pattern="hub",
    )
    write_pattern_instance(
        tmp_path,
        "sat_widget_details",
        "satellite",
        {
            "description": "Widget names as history",
            "owner": "analytics",
            "parent": {"model": "hub_widget", "key": "widget_id"},
            "input_models": ["stg_widgets"],
            "record_source": "erp",
            "attribute_columns": ["widget_name"],
            "unit_tests": [
                {
                    "name": "sat_widget_details__name_is_held",
                    "given": [
                        {
                            "input": "stg_widgets",
                            "rows": [{"widget_id": 1, "widget_name": "alpha"}],
                        }
                    ],
                    "expect": {"rows": [{"widget_name": "alpha"}]},
                    "overrides": {"macros": {"is_incremental": True}},
                }
            ],
        },
        pattern="satellite",
    )
    assert main(["generate", "--write", "--project-dir", str(tmp_path)]) == 0
    return tmp_path / "models" / "_generated" / "tests"


