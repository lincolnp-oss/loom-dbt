def test_canonical_keys_carried(generated_project: Path) -> None:
    by_name = _entries_by_name(generated_project)
    failures: list[str] = []
    for name, generator, _ in CANONICAL_INSTANCES:
        data = by_name[name]
        resolved = resolve_output_columns(data, by_name)
        if resolved is None:
            # Bronze is source-shaped by design: its columns are the
            # source's, undeterminable from metadata. Every other
            # canonical instance must be determinable.
            if generator != "bronze":
                failures.append(
                    f"{name} ({generator}): resolver returned None"
                )
            continue
        columns = [c.name for c in resolved]
        if not columns:
            failures.append(f"{name} ({generator}): resolver returned no columns")
        for key in EXPECTED_KEYS.get(name, []):
            if key not in columns:
                failures.append(
                    f"{name} ({generator}): key column {key!r} not carried; "
                    f"resolver returned {columns}"
                )
    assert not failures, "\n".join(failures)


def test_contract_block_present_iff_opted_in(generated_project: Path) -> None:
    by_name = _entries_by_name(generated_project)
    failures: list[str] = []
    for name, generator, _ in CANONICAL_INSTANCES:
        data = by_name[name]
        plain = model_properties_entry(data, DIALECTS["duckdb"], by_name)
        if plain is not None and "config" in plain:
            failures.append(
                f"{name} ({generator}): contract config present without opt-in"
            )
        opted = dict(data)
        opted["contract_enforced"] = True
        entry = model_properties_entry(opted, DIALECTS["duckdb"], by_name)
        if entry is None:
            failures.append(
                f"{name} ({generator}): no properties entry for opted-in model"
            )
            continue
        enforced = (
            entry.get("config", {}).get("contract", {}).get("enforced")
        )
        if enforced is not True:
            failures.append(
                f"{name} ({generator}): opted-in entry lacks "
                f"config.contract.enforced=true (got {entry.get('config')!r})"
            )
    assert not failures, "\n".join(failures)


def test_negative_contract_mechanics() -> None:
    failures: list[str] = []
    for name, generator, _ in CANONICAL_INSTANCES:
        if name in {n for n, _, _ in CANONICAL_INSTANCES} and any(
            other == name and other_gen != generator
            for other, other_gen, _ in CANONICAL_INSTANCES
        ):
            continue  # same instance name under two generators: none today
        data = expanded_record(name)
        for param in GENERATOR_CONTRACTS[generator]:
            if not param.required:
                continue
            broken = {k: v for k, v in data.items() if k != param.name}
            errors = validate_against_contract("canonical", broken)
            if not any(param.name in error for error in errors):
                failures.append(
                    f"{generator}: missing required param {param.name!r} "
                    f"not reported (errors: {errors})"
                )
        broken = dict(data)
        broken["bogus_param_xyz"] = 1
        errors = validate_against_contract("canonical", broken)
        if not any("bogus_param_xyz" in error for error in errors):
            failures.append(
                f"{generator}: unknown param not reported (errors: {errors})"
            )
    assert not failures, "\n".join(failures)


def test_canonical_chain_executes_on_duckdb(generated_project: Path) -> None:
    duckdb = pytest.importorskip("duckdb")
    conn = duckdb.connect(":memory:")
    for table, (columns, rows) in STUB_SOURCES.items():
        cols = ", ".join(
            f"{c} {'INTEGER' if c in {'id', 'order_id', 'customer_id', 'quantity'} else 'VARCHAR'}"
            for c in columns
        )
        conn.execute(f"CREATE TABLE {table} ({cols})")
        placeholders = ", ".join("?" for _ in columns)
        conn.executemany(f"INSERT INTO {table} VALUES ({placeholders})", rows)
    sql_by_stem = {
        path.stem: path for path in generated_project.rglob("*.sql")
    }
    failures: list[str] = []
    executed: dict[str, int] = {}
    for name, generator, params in CANONICAL_INSTANCES:
        if generator in EXECUTES_EXEMPT_GENERATORS:
            continue
        is_standard_satellite = generator == "satellite" and (
            params.get("variant") in (None, "standard")
        )
        stems = [name] + ([f"{name}_current"] if is_standard_satellite else [])
        for stem in stems:
            path = sql_by_stem.get(stem)
            if path is None:
                failures.append(f"{stem}: no generated file to execute")
                continue
            text = path.read_text(encoding="utf-8")
            is_view = "materialized='view'" in text or stem.endswith("_current")
            compiled = compile_sql(text)
            kind = "VIEW" if is_view else "TABLE"
            try:
                conn.execute(f"CREATE OR REPLACE {kind} {stem} AS {compiled}")
                executed[stem] = conn.execute(
                    f"SELECT COUNT(*) FROM {stem}"
                ).fetchone()[0]
            except Exception as exc:  # noqa: BLE001 - collected per instance
                failures.append(f"{stem} ({generator}): {exc}")
    assert not failures, "\n".join(failures)
    # Stub cardinalities flow through the vault chain unchanged.
    assert executed.get("hub_customer") == 2
    assert executed.get("link_order_customer") == 2
    assert executed.get("fact_orders") == 2


def test_canonical_instance_count_matches_registry() -> None:
    # One canonical instance at minimum per generator (the harness's
    # data contract); duplicates are allowed for chained inputs.
    counts: dict[str, int] = {}
    for _, generator, _ in CANONICAL_INSTANCES:
        counts[generator] = counts.get(generator, 0) + 1
    missing = [g for g in GENERATOR_REGISTRY if counts.get(g, 0) < 1]
    assert not missing, f"generators without canonical instances: {missing}"
    assert set(CANONICAL_BY_NAME) == {name for name, _, _ in CANONICAL_INSTANCES}
