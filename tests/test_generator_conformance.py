"""Registry-driven conformance loop-tests.

Each test iterates every registered generator's canonical instance
(from `generator_conformance`) and collects ALL failures before
asserting, naming the generator/instance in each failure - the
loop-test trade priced in the structural design (one node per
invariant class instead of one per generator).
"""

from __future__ import annotations

from pathlib import Path

import pytest

from generator_conformance import (
    CANONICAL_BY_NAME,
    CANONICAL_INSTANCES,
    EXECUTES_EXEMPT_GENERATORS,
    EXPECTED_KEYS,
    STUB_SOURCES,
    compile_sql,
    expanded_record,
    write_canonical_project,
)
from loom.cli import main
from loom.contracts import GENERATOR_CONTRACTS, validate_against_contract
from loom.dialects import DIALECTS
from loom.generator_registry import GENERATOR_REGISTRY
from loom.inventory import validate_project
from loom.output_columns import resolve_output_columns
from loom.properties import model_properties_entry


@pytest.fixture(scope="module")
def generated_project(tmp_path_factory: pytest.TempPathFactory) -> Path:
    project = tmp_path_factory.mktemp("canon")
    write_canonical_project(project)
    result = main(
        ["generate", "--write", "--project-dir", str(project), "--dialect", "duckdb"]
    )
    assert result == 0
    return project


def _entries_by_name(project: Path) -> dict[str, dict]:
    entries = validate_project(project)
    return {entry.data["name"]: entry.data for entry in entries}


def test_registry_is_fully_canonical() -> None:
    # The harness covers exactly the registered generators: a new
    # generator without a canonical instance fails here first.
    covered = {generator for _, generator, _ in CANONICAL_INSTANCES}
    assert covered == set(GENERATOR_REGISTRY), (
        f"registry generators without canonical instances: "
        f"{sorted(set(GENERATOR_REGISTRY) - covered)}; "
        f"canonical instances for unregistered generators: "
        f"{sorted(covered - set(GENERATOR_REGISTRY))}"
    )


def test_canonical_instances_generate_with_header(
    generated_project: Path,
) -> None:
    failures: list[str] = []
    sql_files = sorted(generated_project.rglob("*.sql"))
    by_stem = {path.stem: path for path in sql_files}
    for name, generator, params in CANONICAL_INSTANCES:
        is_standard_satellite = generator == "satellite" and (
            params.get("variant") in (None, "standard")
        )
        candidates = [name] + ([f"{name}_current"] if is_standard_satellite else [])
        present = [c for c in candidates if c in by_stem]
        if not present:
            failures.append(f"{name} ({generator}): no generated SQL file")
    for path in sql_files:
        text = path.read_text(encoding="utf-8")
        if not text.startswith("-- Generated by Loom"):
            failures.append(f"{path.name}: missing Loom header")
        parts = path.parts
        if any(
            a == "_generated" and b == "staging" for a, b in zip(parts, parts[1:])
        ):
            continue  # staging's provenance line names its source instead
        marker = "-- Generator: "
        if marker not in text:
            failures.append(f"{path.name}: missing Generator provenance line")
        else:
            generator = text.split(marker, 1)[1].split("\n", 1)[0].strip()
            if generator not in GENERATOR_REGISTRY:
                failures.append(
                    f"{path.name}: header names unregistered generator {generator!r}"
                )
    assert not failures, "\n".join(failures)


