@pytest.mark.integration
def test_inline_source_project_builds_end_to_end(tmp_path: Path) -> None:
    """The lifecycle proof: no authored sources.yml anywhere; the
    generated declarations alone let dbt resolve the sources."""
    duckdb = pytest.importorskip(
        "duckdb", reason="requires the integration group"
    )
    dbt = dbt_or_skip()
    project = tmp_path / "inline_runtime"
    (project / "models").mkdir(parents=True)
    (project / "seeds").mkdir()
    (project / "metadata" / "patterns").mkdir(parents=True)
    (project / "metadata" / "instances").mkdir()
    (project / "dbt_project.yml").write_text(
        "name: inline_runtime\nversion: '1.0.0'\nconfig-version: 2\n"
        "profile: inline_runtime\nmodel-paths: ['models']\nseed-paths: ['seeds']\n",
        encoding="utf-8",
    )
    (project / "profiles.yml").write_text(
        duckdb_profiles_yml('inline_runtime', 'inline.duckdb'),
        encoding="utf-8",
    )
    (project / "seeds" / "customers.csv").write_text(
        "id,name\n1,Ada\n2,Grace\n", encoding="utf-8"
    )
    (project / "metadata" / "patterns" / "staging.yml").write_text(
        "name: staging\ngenerator: staging\ndefaults: {owner: test}\n"
        "required_params: [description, inline_source, columns]\n",
        encoding="utf-8",
    )
    (project / "metadata" / "patterns" / "hub.yml").write_text(
        "name: hub\ngenerator: hub\ndefaults: {owner: test}\n"
        "required_params: [description, input_models, business_key]\n",
        encoding="utf-8",
    )
    (project / "metadata" / "instances" / "staging.yml").write_text(
        "pattern: staging\n"
        "instances:\n  - name: stg_customers\n    params:\n"
        "      description: Customer staging.\n"
        "      inline_source: {name: raw, schema: main, table: customers}\n"
        "      columns:\n        - {source: id, alias: customer_id}\n"
        "        - {source: name, alias: customer_name}\n",
        encoding="utf-8",
    )
    (project / "metadata" / "instances" / "hub.yml").write_text(
        "pattern: hub\n"
        "instances:\n  - name: hub_customer\n    params:\n"
        "      description: Customer hub.\n"
        "      input_models: [stg_customers]\n      business_key: customer_id\n",
        encoding="utf-8",
    )

    assert main(["validate", "--project-dir", str(project)]) == 0
    assert main(["generate", "--write", "--project-dir", str(project)]) == 0
    assert (project / "models" / "_generated/staging" / "sources.yml").exists()
    assert not (project / "models" / "sources.yml").exists()

    import os

    env = dict(os.environ)
    for command in ("seed", "build"):
        result = subprocess.run(
            [dbt, command, "--profiles-dir", "."],
            cwd=project,
            env=env,
            capture_output=True,
            text=True,
        )
        assert result.returncode == 0, result.stdout + result.stderr

    connection = duckdb.connect(str(project / "inline.duckdb"), read_only=True)
    try:
        rows = connection.execute(
            "select count(*) from main.hub_customer"
        ).fetchone()
    finally:
        connection.close()
    assert rows == (2,)


# --- Inline sources may declare dbt source freshness -----------------


def test_generate_emits_freshness_for_inline_sources(tmp_path: Path) -> None:
    staging = {
        **_STAGING,
        "inline_source": {
            "name": "raw",
            "schema": "main",
            "table": "customers",
            "loaded_at_field": "updated_at",
            "freshness": {
                "warn_after": {"count": 12, "period": "hour"},
                "error_after": {"count": 24, "period": "hour"},
            },
        },
    }
    write_pattern_instance(
        tmp_path, "stg_customers", "staging", staging, pattern="raw_staging"
    )
    write_pattern_instance(
        tmp_path, "bronze_orders", "bronze", _BRONZE, pattern="medallion_bronze"
    )
    assert main(["generate", "--write", "--project-dir", str(tmp_path)]) == 0
    document = yaml.safe_load(
        (tmp_path / "models" / "_generated/staging" / "sources.yml").read_text(
            encoding="utf-8"
        )
    )
    (source,) = document["sources"]
    tables = {t["name"]: t for t in source["tables"]}
    assert tables["customers"]["loaded_at_field"] == "updated_at"
    assert tables["customers"]["freshness"] == {
        "warn_after": {"count": 12, "period": "hour"},
        "error_after": {"count": 24, "period": "hour"},
    }
    # The bronze table declared no freshness: its entry is unchanged.
    assert tables["orders"] == {"name": "orders"}


def test_generate_without_freshness_is_unchanged(tmp_path: Path) -> None:
    project = _project(tmp_path)
    assert main(["generate", "--write", "--project-dir", str(project)]) == 0
    document = yaml.safe_load(
        (project / "models" / "_generated/staging" / "sources.yml").read_text(
            encoding="utf-8"
        )
    )
    (source,) = document["sources"]
    assert {t["name"]: t for t in source["tables"]} == {
        "customers": {"name": "customers"},
        "orders": {"name": "orders"},
    }


def test_conflicting_freshness_for_one_table_is_rejected(
    tmp_path: Path,
) -> None:
    one = {
        **_STAGING,
        "inline_source": {
            "name": "raw",
            "schema": "main",
            "table": "customers",
            "freshness": {"warn_after": {"count": 12, "period": "hour"}},
        },
    }
    two = {
        "description": "Customer staging (second entry).",
        "owner": "analytics",
        "inline_source": {
            "name": "raw",
            "schema": "main",
            "table": "customers",
            "freshness": {"warn_after": {"count": 6, "period": "hour"}},
        },
        "columns": [{"source": "id", "alias": "customer_id"}],
    }
    write_pattern_instance(
        tmp_path, "stg_customers", "staging", one, pattern="raw_staging"
    )
    write_pattern_instance(
        tmp_path, "stg_customers_b", "staging", two, pattern="raw_staging"
    )
    with pytest.raises(LoomError, match="one freshness declaration"):
        validate_project(tmp_path)
