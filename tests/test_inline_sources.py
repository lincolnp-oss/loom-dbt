def test_conflicting_inline_schemas_for_one_source_are_an_error(
    tmp_path: Path,
) -> None:
    write_pattern_instance(
        tmp_path, "stg_customers", "staging", _STAGING, pattern="raw_staging"
    )
    other = {
        **_STAGING,
        "inline_source": {"name": "raw", "schema": "other", "table": "orders"},
    }
    write_pattern_instance(
        tmp_path, "stg_orders", "staging", other, pattern="raw_staging"
    )
    with pytest.raises(LoomError) as excinfo:
        validate_project(tmp_path)
    assert "one schema" in str(excinfo.value)


