"""Inline sources get a generated source declaration.

Decision (ADR 0024): complete `inline_source` rather than retire it.
Generation emits the dbt source declarations for inline sources that
have no authored declaration - grouped by source name into a
Loom-owned `models/_generated/staging/sources.yml` - so an
inline-source project actually builds. An authored declaration for the
same (source, table) governs and is never re-emitted.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

import pytest
import yaml

from loom.cli import main
from loom.errors import LoomError
from loom.inventory import validate_project
from metadata_helpers import write_pattern_instance
from dbt_harness import dbt_or_skip, duckdb_profiles_yml

_STAGING = {
    "description": "Customer staging.",
    "owner": "analytics",
    "inline_source": {"name": "raw", "schema": "main", "table": "customers"},
    "columns": [{"source": "id", "alias": "customer_id"}],
}
_BRONZE = {"inline_source": {"name": "raw", "table": "orders"}}


def _project(tmp_path: Path) -> Path:
    write_pattern_instance(
        tmp_path, "stg_customers", "staging", _STAGING, pattern="raw_staging"
    )
    write_pattern_instance(
        tmp_path, "bronze_orders", "bronze", _BRONZE, pattern="medallion_bronze"
    )
    return tmp_path


def test_generate_emits_grouped_sources_document(tmp_path: Path) -> None:
    project = _project(tmp_path)
    assert main(["generate", "--write", "--project-dir", str(project)]) == 0
    path = project / "models" / "_generated/staging" / "sources.yml"
    assert path.exists()
    text = path.read_text(encoding="utf-8")
    assert text.startswith("# Generated by Loom")
    document = yaml.safe_load(text)
    assert document["version"] == 2
    (source,) = document["sources"]
    assert source["name"] == "raw"
    assert source["schema"] == "main"
    assert {t["name"] for t in source["tables"]} == {"customers", "orders"}


def test_generated_sources_document_is_not_treated_as_authored(
    tmp_path: Path,
) -> None:
    """Re-validation after generation must not see Loom's own sources
    document as an authored declaration (or nothing would validate)."""
    project = _project(tmp_path)
    assert main(["generate", "--write", "--project-dir", str(project)]) == 0
    validate_project(project)  # must not raise
    assert (
        main(
            [
                "generate",
                "--check",
                "--project-dir",
                str(project),
                "--dialect",
                "duckdb",
            ]
        )
        == 0
    )


def test_authored_declaration_governs_and_is_not_reemitted(
    tmp_path: Path,
) -> None:
    """Bronze has no source_ref alternative, so it may name a source an
    authored file declares (the quickstart's bronze does exactly
    this): the authored declaration governs and generation must not
    emit a duplicate. Staging keeps its stricter rule - an authored
    source name is referenced with source_ref, never inline."""
    staging = {
        **_STAGING,
        "inline_source": {"name": "feed", "schema": "main", "table": "customers"},
    }
    write_pattern_instance(
        tmp_path, "stg_customers", "staging", staging, pattern="raw_staging"
    )
    write_pattern_instance(
        tmp_path, "bronze_orders", "bronze", _BRONZE, pattern="medallion_bronze"
    )
    project = tmp_path
    models = project / "models"
    models.mkdir(parents=True, exist_ok=True)
    (models / "sources.yml").write_text(
        "version: 2\nsources:\n  - name: raw\n    schema: main\n"
        "    tables:\n      - name: orders\n",
        encoding="utf-8",
    )
    assert main(["generate", "--write", "--project-dir", str(project)]) == 0
    document = yaml.safe_load(
        (models / "_generated/staging" / "sources.yml").read_text(
            encoding="utf-8"
        )
    )
    # The bronze 'raw' source is authored, so it is not emitted at all;
    # only the undeclared 'feed' source appears.
    (source,) = document["sources"]
    assert source["name"] == "feed"
    assert [t["name"] for t in source["tables"]] == ["customers"]


