"""Dialect type rendering + the properties emitter."""
from __future__ import annotations

import yaml

from loom.dialects import DIALECTS, get_dialect, render_data_type
from loom.properties import merge_properties, render_properties


def _document(yaml_text: str) -> dict:
    assert yaml_text.startswith("# Generated by Loom\n")
    return yaml.safe_load(yaml_text)


def test_text_spelling_matches_dialect_string_type() -> None:
    for dialect in DIALECTS.values():
        assert render_data_type(dialect, "text") == dialect.string_type


def test_render_data_type_per_dialect() -> None:
    assert render_data_type(get_dialect("duckdb"), "integer") == "INTEGER"
    assert render_data_type(get_dialect("bigquery"), "integer") == "INT64"
    assert render_data_type(get_dialect("clickhouse"), "timestamp") == "DateTime"
    assert render_data_type(get_dialect("azuresynapse"), "boolean") == "BIT"
    assert render_data_type(get_dialect("snowflake"), "timestamp") == "TIMESTAMP_NTZ"


def test_render_decimal_types() -> None:
    assert render_data_type(get_dialect("duckdb"), "decimal(10,2)") == "DECIMAL(10,2)"
    assert render_data_type(get_dialect("bigquery"), "decimal(10, 2)") == "NUMERIC(10,2)"
    assert render_data_type(get_dialect("clickhouse"), "decimal(10,2)") == "Decimal(10,2)"
    assert render_data_type(get_dialect("snowflake"), "decimal(10,2)") == "NUMBER(10,2)"


def test_render_data_type_rejects_unknown_and_bare_decimal() -> None:
    dialect = get_dialect("duckdb")
    assert render_data_type(dialect, "varchar") is None
    assert render_data_type(dialect, "decimal") is None
    assert render_data_type(dialect, "decimal(10)") is None


_DIMENSION = {
    "name": "dim_customers",
    "generator": "dimension",
    "description": "Customer dimension",
    "input_models": ["hub_customer"],
    "natural_key": "customer_id",
    "surrogate_key": "customer_sk",
    "attribute_columns": ["customer_hk"],
}


def test_properties_for_dimension_duckdb() -> None:
    text = render_properties(dict(_DIMENSION), get_dialect("duckdb"))
    doc = _document(text)
    (model,) = doc["models"]
    assert model["name"] == "dim_customers"
    assert model["description"] == "Customer dimension"
    columns = {c["name"]: c for c in model["columns"]}
    assert list(columns) == ["customer_sk", "customer_id", "customer_hk", "__loaded_at"]
    assert columns["customer_sk"]["data_type"] == "BIGINT"
    assert columns["__loaded_at"]["data_type"] == "TIMESTAMP"
    # Attribute and natural-key columns carry practitioner-data types:
    # Loom does not fix them, so no data_type is published.
    assert "data_type" not in columns["customer_id"]
    assert "data_type" not in columns["customer_hk"]
    # Descriptive only: no contract stanza anywhere.
    assert "contract" not in text


def test_properties_for_dimension_bigquery_spellings() -> None:
    text = render_properties(dict(_DIMENSION), get_dialect("bigquery"))
    doc = _document(text)
    columns = {c["name"]: c for c in doc["models"][0]["columns"]}
    assert columns["customer_sk"]["data_type"] == "INT64"
    assert columns["__loaded_at"]["data_type"] == "TIMESTAMP"


def test_properties_use_declared_docs_and_types() -> None:
    params = dict(
        _DIMENSION,
        column_docs={"customer_id": "CRM customer identifier"},
        column_types={"customer_id": "integer", "customer_hk": "text"},
    )
    text = render_properties(params, get_dialect("duckdb"))
    doc = _document(text)
    columns = {c["name"]: c for c in doc["models"][0]["columns"]}
    assert columns["customer_id"]["description"] == "CRM customer identifier"
    assert columns["customer_id"]["data_type"] == "INTEGER"


