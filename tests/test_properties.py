def test_merge_properties_into_test_document() -> None:
    """dbt allows one schema description per model: the properties
    entry merges into the data-test document, tested columns keep
    their tests and gain types, untested derivable columns append."""
    test_document = {
        "version": 2,
        "models": [
            {
                "name": "hub_customer",
                "columns": [
                    {"name": "customer_hk", "tests": ["unique", "not_null"]}
                ],
            }
        ],
    }
    entry = {
        "name": "hub_customer",
        "description": "Customer hub",
        "columns": [
            {"name": "customer_hk", "data_type": "VARCHAR"},
            {"name": "customer_id"},
        ],
    }
    merged = merge_properties(test_document, entry)
    (model,) = merged["models"]
    assert model["description"] == "Customer hub"
    columns = {c["name"]: c for c in model["columns"]}
    assert list(columns) == ["customer_hk", "customer_id"]
    assert columns["customer_hk"]["tests"] == ["unique", "not_null"]
    assert columns["customer_hk"]["data_type"] == "VARCHAR"


